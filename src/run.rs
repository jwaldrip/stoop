fn hook_max_age(o: &Opts) -> u64 {
    o.max_age
        .or_else(|| {
            std::env::var("STOOP_MAX_AGE")
                .ok()
                .and_then(|v| parse_age(&v).ok())
        })
        .unwrap_or(DEFAULT_MAX_AGE)
}

type RecoveredHooks = Vec<(units::hook::Hook, String)>;

fn recover_hooks(
    o: &Opts,
    root: &Path,
    cwd: &str,
    store: &Path,
    scope: Option<&str>,
    max_age: u64,
) -> (Vec<String>, Result<RecoveredHooks, String>) {
    let mut warnings = Vec::new();
    let records = match units::hook_store::records(store, now(), max_age) {
        Ok(records) => records,
        Err(warning) => {
            if !o.quiet {
                warnings.push(warning);
            }
            return (warnings, Ok(Vec::new()));
        }
    };
    let mut found: Vec<(units::hook::Hook, String)> = Vec::new();
    let mut configured = false;
    for record in records.into_iter().filter(|record| {
        record.cwd == cwd && record.scope.as_deref() == scope && record.label == o.key
    }) {
        let words: Vec<OsString> = record.argv.into_iter().map(OsString::from).collect();
        let Ok(Some(parsed)) = units::hook::parse(&words) else {
            continue;
        };
        if !parsed.expanded_matches(&o.argv) {
            continue;
        }
        let (warning, prepared) = units::config::finish(root, cwd, &words, parsed);
        if let Some(warning) = warning {
            if !warnings.contains(&warning) {
                warnings.push(warning);
            }
        }
        match prepared {
            Ok(prepared) => {
                configured |= prepared.config.key_source().is_some();
                if prepared.invalid {
                    return (warnings, Err("the recorded hook has invalid configuration; quote the placeholder or use --literal".into()));
                }
                if let Some(candidate) = prepared.hook {
                    if hook_key_with_config(
                        &candidate,
                        record.label.as_deref(),
                        cwd,
                        scope,
                        prepared.config.key_source(),
                        prepared.invalid,
                    ) != record.key
                    {
                        return (warnings, Err("the recorded hook's full form changed; quote the placeholder or use --literal".into()));
                    }
                    if !found.iter().any(|(known, _)| known.argv == candidate.argv) {
                        found.push((candidate, record.key));
                    }
                }
            }
            Err(error) => return (warnings, Err(error)),
        }
    }
    if configured && found.len() > 1 {
        return (
            warnings,
            Err(
                "recorded hooks have different full forms; quote the placeholder or use --literal"
                    .into(),
            ),
        );
    }
    (warnings, Ok(found))
}

/// The error that stops a placeholder argv before anything runs, if there is one.
pub fn hook_refusal(o: &Opts) -> Option<String> {
    let cwd = std::env::current_dir().unwrap_or_else(|_| PathBuf::from("."));
    let root = root_for(o, &cwd);
    let rel_cwd = cwd_key(&root, &cwd);
    let (warning, prepared) = units::config::prepare(&root, &rel_cwd, &o.argv, o.literal);
    match prepared {
        Err(error) => {
            if let Some(warning) = warning {
                eprintln!("{warning}");
            }
            Some(error)
        }
        Ok(prepared) if prepared.hook.is_none() && !o.literal => {
            let store = store_for(o, &cwd, &root);
            let scope = shared_scope(&root, &store);
            let (warnings, recovered) = recover_hooks(
                o,
                &root,
                &rel_cwd,
                &store,
                scope.as_deref(),
                hook_max_age(o),
            );
            if let Err(error) = recovered {
                for warning in warnings {
                    eprintln!("{warning}");
                }
                Some(error)
            } else {
                None
            }
        }
        Ok(_) => None,
    }
}

/// The variables that carry a placeholder's value (spec section 4.7). Stoop owns them for each run.
const HOOK_ENV: [&str; 5] = [
    "STOOP_CHANGED",
    "STOOP_CHANGED_FILE",
    "STOOP_CHANGED_INPUTS",
    "STOOP_CHANGED_INPUTS_FILE",
    "STOOP_UNITS",
];

/// Set the hook variables for the child. A hook exports all of them, empty. Any other run only
/// replaces an inherited value, and names it unless `warn` is false.
fn clear_hook_env(hook: bool, warn: bool) {
    for name in HOOK_ENV {
        let inherited = std::env::var_os(name).is_some_and(|value| !value.is_empty());
        if inherited && warn {
            eprintln!("stoop: ignoring inherited {name}; the shell may already have expanded it");
        }
        if hook || std::env::var_os(name).is_some() {
            std::env::set_var(name, "");
        }
    }
}

/// Remove the hook records stored under one key. A damaged catalog is a warning.
pub fn forget_hook_records(o: &Opts, key: &str) -> Result<bool, String> {
    let cwd = std::env::current_dir().unwrap_or_else(|_| PathBuf::from("."));
    let root = root_for(o, &cwd);
    units::hook_store::forget(&store_for(o, &cwd, &root), key)
}

/// Forget what was learned about environment variables under `key`. Returns whether anything was.
pub fn forget_volatile(o: &Opts, key: &str) -> Result<bool, String> {
    let cwd = std::env::current_dir().unwrap_or_else(|_| PathBuf::from("."));
    let root = root_for(o, &cwd);
    volatile::forget(&store_for(o, &cwd, &root), key)
}

/// `stoop ls` lines for the names learned as bookkeeping under the current salt.
pub fn volatile_listing(o: &Opts) -> Result<Vec<String>, String> {
    let cwd = std::env::current_dir().unwrap_or_else(|_| PathBuf::from("."));
    let root = root_for(o, &cwd);
    let salt = env_salt();
    let learned = volatile::list(
        &store_for(o, &cwd, &root),
        &volatile::salt_id(salt.as_deref()),
    )?;
    let mut lines = Vec::new();
    for (key, names) in learned {
        for (name, runs) in names {
            lines.push(format!(
                "volatile\t{key}\tignores {}\tlearned after {runs} runs",
                volatile::safe(&name)
            ));
        }
    }
    Ok(lines)
}

/// Learning is on unless `--no-learn-volatile` or `STOOP_LEARN_VOLATILE` turns it off. An empty,
/// `0`, `false`, `no` or `off` value is off. A value that is not UTF-8 is off as well: a run that
/// does not learn counts more, so it skips less.
pub fn learning_on(o: &Opts) -> bool {
    if o.no_learn_volatile {
        return false;
    }
    match std::env::var_os("STOOP_LEARN_VOLATILE") {
        None => true,
        Some(value) => match value.to_str() {
            Some(text) => !matches!(
                text.trim().to_ascii_lowercase().as_str(),
                "" | "0" | "false" | "no" | "off"
            ),
            None => false,
        },
    }
}

fn run_internal(mut o: Opts, explain: bool, observe_runners: bool) -> Outcome {
    let initial_key = o.key.clone().unwrap_or_default();
    if o.argv.is_empty() {
        eprintln!("stoop: no command given");
        return Outcome {
            status: 2,
            key: initial_key,
            how: How::Untraced,
        };
    }
    if !o.pass_env.is_empty() {
        if explain {
            if !o.quiet {
                eprintln!("stoop: would run without a proof: OIDC request credentials are explicitly passed");
            }
            return Outcome {
                status: 1,
                key: initial_key,
                how: How::Unrecorded("OIDC request credentials passed".into()),
            };
        }
        if !o.quiet {
            eprintln!("stoop: running untraced without a proof: OIDC request credentials are explicitly passed");
        }
        return Outcome {
            status: plain(&o.argv, &o.pass_env),
            key: initial_key,
            how: How::Unrecorded("OIDC request credentials passed".into()),
        };
    }
    let cwd = std::env::current_dir().unwrap_or_else(|_| PathBuf::from("."));
    let root = root_for(&o, &cwd);
    let rel_cwd = cwd_key(&root, &cwd);
    let store_path = store_for(&o, &cwd, &root);
    let scope = shared_scope(&root, &store_path);
    let literal = o.literal || !observe_runners;
    let (warning, prepared) = units::config::prepare(&root, &rel_cwd, &o.argv, literal);
    if let Some(warning) = warning {
        eprintln!("{warning}");
    }
    let units::config::Prepared {
        mut hook,
        config,
        invalid: config_invalid,
        independent_false,
    } = match prepared {
        Ok(prepared) => prepared,
        Err(error) => {
            eprintln!("stoop: {error}");
            return Outcome {
                status: 2,
                key: initial_key,
                how: How::Untraced,
            };
        }
    };
    // A placeholder that reached stoop intact: the shell expanded nothing into it.
    let intact = hook.is_some();
    if let Some(h) = &hook {
        o.argv.clone_from(&h.argv);
    }
    let max_age = hook_max_age(&o);
    // An erased hook runs its recorded full form and never skips. Configured conflicting
    // forms, invalid configuration, or changed configuration identity are refused.
    let mut expanded = false;
    let mut recovered_key = None;
    let mut matches = 0;
    if !literal && hook.is_none() {
        let (warnings, recovered) =
            recover_hooks(&o, &root, &rel_cwd, &store_path, scope.as_deref(), max_age);
        for warning in warnings {
            eprintln!("{warning}");
        }
        let mut found = match recovered {
            Ok(found) => found,
            Err(error) => {
                eprintln!("stoop: {error}");
                return Outcome {
                    status: 2,
                    key: initial_key,
                    how: How::Untraced,
                };
            }
        };
        matches = found.len();
        if matches == 1 {
            let (candidate, key) = found.swap_remove(0);
            recovered_key = Some(key);
            o.argv.clone_from(&candidate.argv);
            hook = Some(candidate);
            expanded = true;
        }
    }
    let bypass = expanded || matches > 1;
    // Stoop owns the hook variables for its child. A hook exports them empty. Any other run
    // replaces an inherited value and names it, unless a placeholder reached stoop intact.
    if !literal {
        clear_hook_env(hook.is_some(), !intact);
    }
    let key = recovered_key
        .or_else(|| {
            hook.as_ref().map(|h| {
                hook_key_with_config(
                    h,
                    o.key.as_deref(),
                    &rel_cwd,
                    scope.as_deref(),
                    config.key_source(),
                    config_invalid,
                )
            })
        })
        .unwrap_or_else(|| {
            o.key
                .as_deref()
                .map(|key| {
                    if o.shell_key {
                        crate::stepkey::scoped(key, scope.as_deref())
                    } else {
                        sanitize(key)
                    }
                })
                .unwrap_or_else(|| default_key(&o.argv, &rel_cwd, scope.as_deref()))
        });
    // One decision line for an expanded shape, an ambiguous shape or an empty value. Explain
    // prints it in place of the run and runs nothing; a run prints it as its hint.
    let note = if expanded {
        hook.as_ref().map(|h| {
            if explain {
                units::hook::expanded_explain(h)
            } else {
                units::hook::expanded_line(h)
            }
        })
    } else if matches > 1 {
        Some(units::hook::ambiguous_line(&o.argv, matches, explain))
    } else if !literal && hook.is_none() {
        units::hook::empty_value_line(&o.argv, explain)
    } else {
        None
    };
    if let Some(line) = note {
        eprintln!("{line}");
        if explain {
            return Outcome {
                status: 1,
                key,
                how: How::Untraced,
            };
        }
    }
    if let Some(h) = &hook {
        if !expanded && !explain && !o.no_record {
            // A record holds text. A hook template with an argument that is not UTF-8 is not
            // recorded, so a shell-erased form of this hook is not recognised. The whole-command
            // proof is keyed by the exact bytes and is still recorded.
            let words = recordable_argv(&h.original);
            match words {
                Some(argv) => {
                    let record = units::hook_store::Record {
                        key: key.clone(),
                        argv,
                        cwd: rel_cwd.clone(),
                        scope: scope.clone(),
                        label: o.key.clone(),
                        created: now(),
                    };
                    if let Err(warning) = units::hook_store::record(&store_path, record) {
                        if !o.quiet {
                            eprintln!("{warning}");
                        }
                    }
                }
                None if !o.quiet => {
                    eprintln!(
                        "stoop: the hook template is not recorded, so a shell-erased form of this hook will not be recognised"
                    );
                }
                None => {}
            }
        }
    }
    // STOOP_OFF runs a hook's first-run form without tracing, and its hints still print above.
    if env_switch("STOOP_OFF", true) && !explain {
        return Outcome {
            status: plain(&o.argv, &[]),
            key: initial_key,
            how: How::Untraced,
        };
    }
    let volatile_store = store_path.clone();
    let store = Store::new(store_path);
    if explain && !o.quiet {
        let dir = if rel_cwd.is_empty() { "." } else { &rel_cwd };
        eprintln!("stoop: dir {dir:?}");
    }
    if !trace::supported() {
        if explain {
            match &hook {
                Some(h) => eprintln!(
                    "stoop: would run full {key} (not traced: {}): removed {}, argv {}",
                    trace::UNAVAILABLE,
                    units::hook::show(&h.removed),
                    units::hook::render(&h.argv)
                ),
                None => eprintln!(
                    "stoop: would run {key}: not traced ({}); no proof can be used",
                    trace::UNAVAILABLE
                ),
            }
            return Outcome {
                status: 1,
                key,
                how: How::Untraced,
            };
        }
        #[cfg(target_os = "macos")]
        if env_switch("STOOP_DTRACE_DIAGNOSTIC", false) {
            if let Some(outcome) = dtrace_diagnostic(&o, &cwd, &key) {
                return outcome;
            }
        }
        if !o.quiet {
            match &hook {
                Some(h) => eprintln!(
                    "stoop: run full {key} (no compatible tracer): removed {}",
                    units::hook::show(&h.removed)
                ),
                None => eprintln!("stoop: run {key}: no compatible tracer"),
            }
            eprintln!(
                "stoop: not traced ({}); running without a proof",
                trace::UNAVAILABLE
            );
        }
        return Outcome {
            status: plain(&o.argv, &[]),
            key,
            how: How::Untraced,
        };
    }
    let full_reason = if env_switch("STOOP_FULL", true) {
        Some("STOOP_FULL is set".to_string())
    } else if hook.is_some() && config_invalid {
        Some("invalid unit configuration".to_string())
    } else if hook.is_some() && independent_false {
        Some("suite is not independent".to_string())
    } else if hook.is_some() {
        let sync = o.sync.clone().or_else(|| env_str("STOOP_SYNC"));
        units::policy::forced_reason(
            &root,
            &config,
            sync.as_deref(),
            o.sync_write || env_flag("STOOP_SYNC_WRITE"),
        )
    } else {
        None
    };
    let max_age = o
        .max_age
        .or_else(|| {
            std::env::var("STOOP_MAX_AGE")
                .ok()
                .and_then(|v| parse_age(&v).ok())
        })
        .unwrap_or(DEFAULT_MAX_AGE);
    // The words are mentioned as lossy text: the names a command can mention are ASCII.
    let mention = format!(
        "{} {}",
        o.argv
            .iter()
            .map(|word| word.to_string_lossy())
            .collect::<Vec<_>>()
            .join(" "),
        o.mention
    );
    let candidates = ambient_env(&mention, &o.ignore_env);
    let salt = env_salt();
    let volatile = volatile::decide(&volatile::Request {
        store: &volatile_store,
        key: &key,
        candidates: &candidates,
        mention: &mention,
        forced: &o.env,
        ignore: &o.ignore_env,
        salt: salt.as_deref(),
        learn: learning_on(&o),
        // A run that does not write its record, or only explains, observes in memory: it must not
        // change what a trusted run has learned.
        persist: !explain && !o.no_record,
        now: now(),
    });
    for line in &volatile.changes {
        if !o.quiet {
            eprintln!("stoop: {line}");
        }
    }
    if let Some(warning) = &volatile.warning {
        if !o.quiet {
            eprintln!("{warning}");
        }
    }
    if explain && !o.quiet {
        for (name, why) in &volatile.plan.excluded {
            eprintln!("stoop: ignoring env {}: {why}", volatile::safe(name));
        }
    }
    let env_excluded: Vec<String> = volatile
        .plan
        .excluded
        .iter()
        .map(|(name, _)| name.clone())
        .collect();
    let env_now = env_hashes(&volatile.plan.counted, salt.as_deref());
    let excluded_now: std::collections::BTreeSet<&String> = env_excluded.iter().collect();

    let remote = o
        .sync
        .clone()
        .or_else(|| env_str("STOOP_SYNC"))
        .and_then(|spec| {
            let write = o.sync_write || env_flag("STOOP_SYNC_WRITE");
            match Remote::from_spec(&spec, &root, write) {
                Ok(r) => Some(r),
                Err(e) => {
                    eprintln!("stoop: sync: {e}");
                    None
                }
            }
        });

    // 1. Is there a proof whose inputs all still match?
    let t0 = Instant::now();
    let mut proofs = if bypass { Vec::new() } else { store.load(&key) };
    let mut pulled = false;
    let mut probe_now: Option<Option<BTreeMap<String, String>>> = None;
    let mut why;
    let mut hit_idx: Option<usize>;
    loop {
        why = String::from("no proof yet");
        hit_idx = None;
        for (i, p) in proofs.iter().enumerate() {
            // A proof whose recorded reason says the run read a path it also wrote, or read a file it
            // then removed, cannot justify a skip: the change was observed but cannot be replayed.
            if p.unplannable.iter().any(|reason| is_skip_veto(reason)) {
                continue;
            }
            let expired = max_age > 0 && now().saturating_sub(p.created) > max_age;
            let diffs: Vec<(String, &'static str)> = if p.provenance.is_none() {
                vec![("provenance".to_string(), "missing; run once to refresh")]
            } else if !p.provenance.as_ref().is_some_and(|p| p.is_current()) {
                vec![("provenance".to_string(), "changed")]
            } else if p.cwd.as_deref() != Some(rel_cwd.as_str()) {
                vec![("directory".to_string(), "changed")]
            } else if p.scope != scope {
                vec![("repository".to_string(), "changed")]
            } else if expired {
                vec![("proof".to_string(), "expired")]
            } else if p.env != env_now {
                vec![("env".to_string(), "changed")]
            } else if p
                .env_excluded
                .iter()
                .collect::<std::collections::BTreeSet<_>>()
                != excluded_now
            {
                vec![("env exclusions".to_string(), "changed")]
            } else {
                let mut d: Vec<(String, &'static str)> = verify(&root, &p.inputs, explain)
                    .into_iter()
                    .map(|m| (m.path, m.why))
                    .collect();
                if d.is_empty() {
                    // Inputs match, but a skip also needs what the run produced to be in place.
                    d = verify(&root, &p.outputs, explain)
                        .into_iter()
                        .map(|m| {
                            (
                                format!("output {}", m.path),
                                if m.why == "removed" { "missing" } else { m.why },
                            )
                        })
                        .collect();
                }
                d
            };
            let mut diffs = diffs;
            if diffs.is_empty() && (!p.probes.is_empty() || !o.probes.is_empty()) {
                // External state is checked last: it can be slow, and files rule most proofs out first.
                let fresh = probe_now.get_or_insert_with(|| run_probes(&o.probes, &cwd, o.quiet));
                match fresh {
                    None => diffs.push(("probe".to_string(), "failed")),
                    Some(m) if *m != p.probes => {
                        let which = m
                            .keys()
                            .chain(p.probes.keys())
                            .find(|k| m.get(*k) != p.probes.get(*k))
                            .cloned()
                            .unwrap_or_else(|| "probe".to_string());
                        diffs.push((format!("probe `{which}`"), "changed"));
                    }
                    Some(_) => {}
                }
            }
            if diffs.is_empty() {
                hit_idx = Some(i);
                break;
            }
            if i == 0 {
                let first = &diffs[0];
                let more = if diffs.len() > 1 {
                    format!(" (+{} more)", diffs.len() - 1)
                } else {
                    String::new()
                };
                why = format!("{} {}{}", shown_text(&first.0), first.1, more);
            }
            if explain {
                eprintln!("proof {} ({}):", i + 1, ago(p.created));
                for (path, w) in diffs.iter().take(20) {
                    eprintln!("  {w}: {}", shown_text(path));
                }
            }
        }
        // A miss with a remote configured: someone else may already have proved this.
        if hit_idx.is_some() || pulled || remote.is_none() || bypass {
            break;
        }
        pulled = true;
        match remote.as_ref().map(|r| r.pull(&store, &key)) {
            Some(Ok(0)) | None => break,
            Some(Ok(_)) => proofs = store.load(&key),
            Some(Err(e)) => {
                eprintln!("stoop: sync: could not fetch proofs ({e}); continuing");
                break;
            }
        }
    }
    let hit: Option<&Proof> = hit_idx.map(|i| &proofs[i]);
    if let Some(p) = hit {
        if full_reason.is_none() {
            if !o.quiet {
                eprintln!(
                    "stoop: skip {key}: {} inputs unchanged since {} ({}ms)",
                    p.inputs.len(),
                    ago(p.created),
                    t0.elapsed().as_millis()
                );
            }
            return Outcome {
                status: 0,
                key,
                how: How::Skipped { proof: p.digest() },
            };
        }
        why = full_reason.clone().unwrap_or_else(|| why.clone());
    }
    if hook.is_some() {
        if let Some(reason) = &full_reason {
            why.clone_from(reason);
        }
    }
    if explain {
        match &hook {
            Some(h) => eprintln!(
                "stoop: would run full {key} ({why}): removed {}, argv {}",
                units::hook::show(&h.removed),
                units::hook::render(&h.argv)
            ),
            None => eprintln!("stoop: would run {key}: {why}"),
        }
        return Outcome {
            status: 1,
            key,
            how: How::Untraced,
        };
    }
    if !o.quiet {
        match &hook {
            Some(h) => eprintln!(
                "stoop: run full {key} ({why}): removed {}",
                units::hook::show(&h.removed)
            ),
            None => eprintln!("stoop: run {key}: {why}"),
        }
    }

    // 2. Run it, watched. Anything that stops the watch from working just runs the command.
    let probes_before = if o.probes.is_empty() {
        Some(BTreeMap::new())
    } else {
        run_probes(&o.probes, &cwd, o.quiet)
    };
    // Declaring a probe is declaring the external dependency, so network use is accepted.
    // The ignore set and the scope are fixed before the run: priors are recorded against them.
    let ignore = Ignore::new(&o.ignore, Some(&root.join(".stoopignore")), &o.transient);
    let real_root = std::fs::canonicalize(&root).unwrap_or_else(|_| root.clone());
    let trace_scope = (!o.no_record).then(|| trace::Scope {
        root: &root,
        real_root: real_root.clone(),
        ignore: &ignore,
        // One attribute snapshot per run, taken before the command can change anything.
        oid_epoch: trace::supported()
            .then(|| crate::oid_attrs::capture(&real_root))
            .flatten()
            .map(Arc::new),
    });
    let mut trace = match trace::run(
        &o.argv,
        &cwd,
        o.allow_network || !o.probes.is_empty(),
        trace_scope.as_ref(),
        observe_runners && !o.no_record && !o.quiet,
    ) {
        Ok(t) => t,
        Err(e) => {
            if !o.quiet {
                eprintln!("stoop: not traced ({e}); running without a proof");
            }
            return Outcome {
                status: plain(&o.argv, &[]),
                key,
                how: How::Untraced,
            };
        }
    };
    if let Some(line) = trace.execs.as_deref().and_then(units::diagnostic) {
        eprintln!("{line}");
    }
    let status = trace.status;
    if status != 0 {
        return Outcome {
            status,
            key,
            how: How::Failed,
        };
    }
    if o.no_record {
        return Outcome {
            status,
            key,
            how: How::Unrecorded("recording disabled".into()),
        };
    }
    // The external state the command saw must still be what it was when it finished.
    let probes = match probes_before {
        None => {
            if !o.quiet {
                eprintln!("stoop: not recorded: a probe failed before the run, so the external state is unknown");
            }
            return Outcome {
                status,
                key,
                how: How::Unrecorded("probe failed".into()),
            };
        }
        Some(before) => {
            if !o.probes.is_empty()
                && run_probes(&o.probes, &cwd, o.quiet).as_ref() != Some(&before)
            {
                if !o.quiet {
                    eprintln!("stoop: not recorded: a probe changed while the command ran");
                }
                return Outcome {
                    status,
                    key,
                    how: How::Unrecorded("probe changed".into()),
                };
            }
            before
        }
    };

    // 3. It passed: write down what it read, what it wrote, and what each written path held before.
    // Attribute and configuration sources that Git reads must still be what they were before the
    // command ran. A change makes the blob ids of this run's inputs untrustworthy, not the run.
    if trace
        .oid_epoch
        .as_deref()
        .is_some_and(|epoch| epoch.watched_changed())
    {
        trace.oid_attrs_changed = true;
    }
    let mut phys = Physical::new(&root, &real_root);
    let written: BTreeSet<String> = trace.keys.values().cloned().collect();
    let checked = build_inputs(&root, &mut phys, &trace, &ignore, &written).and_then(
        |(inputs, read_reasons)| {
            let (outputs, removed, write_reasons) = build_outputs(&real_root, &written, &trace)?;
            Ok((inputs, read_reasons, outputs, removed, write_reasons))
        },
    );
    match checked {
        Ok((inputs, read_reasons, outputs, removed, write_reasons)) => {
            let n = inputs.len();
            let proof = Proof {
                created: now(),
                argv: o
                    .argv
                    .iter()
                    .map(|word| word.to_string_lossy().into_owned())
                    .collect(),
                cwd: Some(rel_cwd.clone()),
                scope: scope.clone(),
                provenance: Some(trace::Provenance::current()),
                env: env_now,
                env_excluded,
                inputs,
                outputs,
                probes,
                removed,
                ignore: Some(ignore.patterns()),
                priors: Some(build_priors(&trace)),
                unplannable: merge_reasons(
                    &trace.unplannable,
                    read_reasons.into_iter().chain(write_reasons).collect(),
                ),
            };
            let digest = proof.digest();
            if let Some(r) = remote.as_ref().filter(|r| r.write) {
                // Fold in anything other runs published since we looked, so a push never
                // drops their proofs.
                if let Err(e) = r.pull(&store, &key) {
                    eprintln!("stoop: sync: could not refresh from the remote ({e}); continuing");
                }
            }
            let saved = match store.save(&key, proof) {
                Ok(()) => {
                    if !o.quiet {
                        eprintln!("stoop: recorded {n} inputs for {key}");
                    }
                    true
                }
                Err(e) => {
                    eprintln!("stoop: could not save proof: {e}");
                    false
                }
            };
            if let Some(r) = remote
                .as_ref()
                .filter(|r| saved && r.write && !o.defer_push)
            {
                if salt.is_none() {
                    // Hashes of every variable go into a file other people can fetch. An
                    // unsalted hash of a low-entropy secret can be guessed offline.
                    eprintln!(
                        "stoop: sync: publishing environment hashes without {SALT_VAR}. In a public repository set it from a repository secret so low-entropy values cannot be guessed offline."
                    );
                }
                match r.push(&store, &key) {
                    Ok(()) if !o.quiet => eprintln!("stoop: published {key} to the remote"),
                    Ok(()) => {}
                    Err(e) => eprintln!("stoop: sync: could not publish ({e}); continuing"),
                }
            }
            return Outcome {
                status,
                key,
                how: if saved {
                    How::Recorded { proof: digest }
                } else {
                    How::Unrecorded("could not save proof".into())
                },
            };
        }
        Err(why) => {
            if !o.quiet {
                eprintln!("stoop: not recorded: {why}");
            }
        }
    }
    Outcome {
        status,
        key,
        how: How::Unrecorded("inputs could not be recorded".into()),
    }
}

/// What the run left behind inside the repository, read once it finished: one entry for each
/// in-scope path it wrote. Still there is an output. Gone again is removed, and the planner
/// removes it with the step. Unreadable or special is a reason the planner cannot replay.
type OutputParts = (Vec<Input>, Vec<String>, Vec<String>);

fn build_outputs(
    real_root: &Path,
    written: &BTreeSet<String>,
    trace: &Trace,
) -> Result<OutputParts, NotRecorded> {
    let keys: Vec<&String> = written.iter().collect();
    let ids = par_map(&keys, |k| {
        identify_post(&real_root.join(k.as_str()), true, false, false)
    });
    let mut outputs = Vec::new();
    let mut removed = Vec::new();
    let mut reasons = Vec::new();
    for (key, (id, post)) in keys.into_iter().zip(ids) {
        let id = id.map(|(id, _)| id);
        if !trace.read_before_write.is_empty() {
            let path = real_root.join(key);
            if trace.read_before_write.contains(&path) {
                let prior = trace.priors.get(key);
                // An absent prior can also be the final state when a verified own removal
                // explains it. The prior is recorded as a runtime input below.
                let own_absence = id.as_deref() == Some("a")
                    && prior.map(String::as_str) == Some("a")
                    && trace.removal_explains_absence(&path);
                let own_removal = id.as_deref() == Some("a")
                    && prior.is_some_and(|prior| prior.as_str() != "a")
                    && matches!(
                        trace.removed_by_run.get(&path),
                        Some(crate::trace::Removal::Unlinked)
                    );
                if own_removal {
                    // The run read the file and then removed it with its own verified unlink. The
                    // prior stays a runtime input, and the proof is never reused by a skip.
                    reasons.push(format!("it read {key} and then removed it"));
                } else if !own_absence {
                    if id
                        .as_deref()
                        .is_none_or(|value| value == "a" || value == "u")
                    {
                        return Err(NotRecorded::Other(format!(
                            "it could not verify the last write to {key}"
                        )));
                    }
                    if id.as_ref() == prior {
                        let settled = trace.settled_outputs.get(&path);
                        if !matches!(settled, Some(Seen::File(_)))
                            || !settled
                                .is_some_and(|seen| identity::compare(seen, &post, None).is_ok())
                        {
                            return Err(NotRecorded::Other(format!(
                                "it could not verify the last write to {key}"
                            )));
                        }
                    }
                }
            }
        }
        match id {
            None => reasons.push(format!("it left {key} unreadable")),
            Some(id) if id == "u" => reasons.push(format!("it left {key} unreadable")),
            Some(id) if id == "a" => removed.push(key.clone()),
            Some(id) => outputs.push(Input {
                path: key.clone(),
                id,
                oid: None,
                oid_basis: None,
            }),
        }
    }
    if written.contains(".stoopignore") {
        reasons.push("it wrote .stoopignore, which the proof's ignore set was read from".into());
    }
    Ok((outputs, removed, reasons))
}

/// The state of each in-scope path before the run first wrote it, sorted by path.
pub fn build_priors(trace: &Trace) -> Vec<Input> {
    trace
        .priors
        .iter()
        .map(|(path, id)| {
            let basis = (!trace.oid_attrs_changed)
                .then(|| trace.prior_oid_bases.get(path))
                .flatten();
            let oid = basis
                .filter(|basis| basis.allows_oid())
                .and_then(|_| trace.prior_oids.get(path).cloned());
            let oid_basis = basis.cloned();
            Input {
                path: path.clone(),
                id: id.clone(),
                oid,
                oid_basis,
            }
        })
        .collect()
}

/// Whether a stored reason forbids a skip: the run read a path it also wrote, or read a file it
/// then removed. Such a record is kept for diagnosis and is never reused.
pub fn is_skip_veto(reason: &str) -> bool {
    reason.ends_with("and also wrote it") || reason.ends_with("and then removed it")
}

/// The proof's reasons: the tracer's first, then the rest, deduplicated and capped at 16. A full
/// list keeps one reason that vetoes a skip, so diagnostics cannot push it out.
fn merge_reasons(first: &[String], more: Vec<String>) -> Vec<String> {
    let mut out: Vec<String> = Vec::new();
    let mut veto: Option<String> = None;
    for why in first.iter().cloned().chain(more) {
        if veto.is_none() && is_skip_veto(&why) {
            veto = Some(why.clone());
        }
        if out.len() < 16 && !out.contains(&why) {
            out.push(why);
        }
    }
    if let Some(veto) = veto.filter(|_| !out.iter().any(|why| is_skip_veto(why))) {
        if out.len() >= 16 {
            out.pop();
        }
        out.push(veto);
    }
    out
}

/// Why a run cannot be recorded. `Changed` names an input that changed while the command ran, so
/// the command may have read other bytes than the record would describe.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum NotRecorded {
    Changed { key: String },
    Other(String),
}

impl NotRecorded {
    fn sort_key(&self) -> &str {
        match self {
            NotRecorded::Changed { key } => key,
            NotRecorded::Other(text) => text,
        }
    }
}

impl std::fmt::Display for NotRecorded {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            NotRecorded::Changed { key } => write!(f, "{key} changed while the command ran"),
            NotRecorded::Other(text) => f.write_str(text),
        }
    }
}

impl From<String> for NotRecorded {
    fn from(text: String) -> Self {
        NotRecorded::Other(text)
    }
}

impl From<&str> for NotRecorded {
    fn from(text: &str) -> Self {
        NotRecorded::Other(text.to_owned())
    }
}

/// A path to compare with its read-time identity once the command has exited.
struct Candidate {
    path: PathBuf,
    key: String,
    inside: bool,
    listed: bool,
    physical_key: Option<String>,
    /// The touched path whose read-time identity covers this candidate.
    source: PathBuf,
    /// The candidate is what a symbolic link at `source` resolved to, so the link's followed
    /// identity covers it rather than a touch of its own.
    followed: bool,
}

/// Compare one candidate with what its source held at the run's first look.
fn check_candidate(trace: &Trace, cand: &Candidate, post: &Post) -> Result<(), NotRecorded> {
    let Some(recorded) = trace.seen.as_ref() else {
        return Ok(());
    };
    let no_identity = || NotRecorded::Other(format!("{} has no read-time identity", cand.key));
    let Some(first) = recorded.get(&cand.source) else {
        return Err(no_identity());
    };
    let seen = if cand.followed {
        match first {
            Seen::Symlink { followed, .. } => followed.as_ref(),
            _ => {
                return Err(NotRecorded::Changed {
                    key: cand.key.clone(),
                })
            }
        }
    } else {
        first
    };
    let empty = identity::Names::new();
    let listing = if cand.listed {
        let Some(listed) = trace.listings.get(&cand.source) else {
            return Err(no_identity());
        };
        // Even a successful own namespace mutation can be followed by a foreign change of the
        // same name. Do not exclude names merely because the command changed them.
        Some((listed, &empty))
    } else {
        None
    };
    identity::compare(seen, post, listing).map_err(|why| match why {
        identity::Refusal::Changed => NotRecorded::Changed {
            key: cand.key.clone(),
        },
        identity::Refusal::OverBudget => NotRecorded::Other(format!(
            "{} changed less than 2 s before it was read and is too large to check (read-time hashing is capped at 1 GiB per run)",
            cand.key
        )),
        identity::Refusal::Unhashable => {
            NotRecorded::Other(format!("{} could not be read to check it", cand.key))
        }
    })
}

/// What the run read, as comparable inputs, or why it cannot be trusted. A read of a path the run
/// wrote is not an input: it reads the run's own output. A read through a link or a symlinked
/// directory is also recorded under the key of the file it reached, so a change to that file is
/// seen. Every candidate is also compared with its read-time identity, so a change made while the
/// command ran refuses the record. The second value holds reasons the planner cannot replay the run.
pub fn build_inputs(
    root: &Path,
    phys: &mut Physical,
    trace: &Trace,
    ignore: &Ignore,
    written: &BTreeSet<String>,
) -> Result<(Vec<Input>, Vec<String>), NotRecorded> {
    if let Some(u) = trace.unsound.first() {
        return Err(u.clone().into());
    }
    let paths = trace
        .touched
        .keys()
        .chain(&trace.written)
        .chain(&trace.created_dirs);
    for path in paths {
        if path.strip_prefix(root).unwrap_or(path).to_str().is_none() {
            return Err("a traced path is not valid UTF-8".into());
        }
    }
    // Symlink targets are serialized as text too. Refuse rather than serialize lossy bytes.
    for path in trace.keys.keys().chain(trace.touched.keys()) {
        let in_repo = path.starts_with(root) || path.starts_with(phys.real());
        if in_repo
            && std::fs::symlink_metadata(path).is_ok_and(|m| m.file_type().is_symlink())
            && std::fs::read_link(path).is_ok_and(|target| target.to_str().is_none())
        {
            return Err("it used a repository symlink with a non-UTF-8 target".into());
        }
    }
    let real_root = phys.real().to_path_buf();
    phys.prefetch(
        trace
            .touched
            .keys()
            .filter_map(|p| p.parent().map(Path::to_path_buf)),
    );
    // Outside outputs are untracked. Resolve each conflict physically first so an outside
    // spelling cannot hide a tracked repository target; retain the first followed link target too.
    for path in &trace.read_write_conflicts {
        let key_for = |candidate: &Path| {
            let base = if candidate.starts_with(&real_root) {
                &real_root
            } else if candidate.starts_with(root) {
                root
            } else {
                return None;
            };
            let key = to_key(base, candidate);
            (!key.is_empty() && !ignore.is_ignored(&key)).then_some(key)
        };
        let recorded_target = trace
            .seen
            .as_ref()
            .and_then(|seen| seen.get(path))
            .and_then(|seen| match seen {
                Seen::Symlink { resolved, .. } => resolved.as_deref(),
                _ => None,
            });
        let physical = phys.locate(path).map(|loc| loc.path);
        let key = if physical.as_deref().is_none_or(|candidate| {
            candidate.starts_with(&real_root) || candidate.starts_with(root)
        }) {
            key_for(path)
        } else {
            None
        };
        let key = key
            .or_else(|| recorded_target.and_then(key_for))
            .or_else(|| physical.as_deref().and_then(key_for));
        if let Some(key) = key {
            return Err(NotRecorded::Other(format!(
                "it read {key} and also wrote it"
            )));
        }
    }
    let mut reasons: Vec<String> = Vec::new();
    let mut reads_git = false;
    // Refusals found while checking the record. The reported one is the first in key order, so
    // the message does not depend on the order the tracer's hash map happens to hold paths in.
    let mut refusals: Vec<NotRecorded> = Vec::new();
    let mut cands: Vec<Candidate> = Vec::new();
    for (lex, touch) in &trace.touched {
        let inside = lex.starts_with(root);
        let key = to_key(root, lex);
        let physical = phys.locate(lex).map(|l| l.path);
        let verified_before_write = trace.read_before_write.contains(lex)
            || physical
                .as_ref()
                .is_some_and(|path| trace.read_before_write.contains(path));
        // The same entry reached under its physical name, when that differs from the spelled one.
        if let Some(pp) = &physical {
            if let Some(rel) = phys.repo_rel(pp) {
                if rel.to_str().is_none() {
                    return Err("it used a path in the repository that is not valid UTF-8".into());
                }
                let pkey = to_key(&real_root, pp);
                if pkey != key {
                    if rel.components().any(|c| is_git_name(c.as_os_str())) {
                        if !ignore.is_ignored(&pkey) {
                            reads_git = true;
                        }
                    } else if ignore.is_ignored(&pkey) {
                    } else if trace.read_before_write.contains(pp) {
                        // The first-read state is recorded from the verified prior below.
                    } else if written.contains(&pkey) {
                        if trace.seen.is_some() && touch.read && !verified_before_write {
                            refusals.push(NotRecorded::Other(format!(
                                "it read {pkey} and also wrote it"
                            )));
                        }
                    } else {
                        cands.push(Candidate {
                            path: pp.clone(),
                            key: pkey.clone(),
                            inside: true,
                            listed: touch.listed,
                            physical_key: Some(pkey),
                            source: lex.clone(),
                            followed: false,
                        });
                    }
                }
            }
        }
        // A lexical key containing `..` does not describe kernel resolution across a symlink. The
        // physical candidate above is the only faithful repository key.
        if lex
            .components()
            .any(|part| matches!(part, std::path::Component::ParentDir))
        {
            continue;
        }
        if key.is_empty() || ignore.is_ignored(&key) {
            continue;
        }
        if inside
            && lex
                .strip_prefix(root)
                .ok()
                .and_then(|r| r.to_str())
                .is_none()
        {
            return Err("it used a path in the repository that is not valid UTF-8".into());
        }
        let physical_key = physical
            .as_deref()
            .and_then(|path| phys.repo_rel(path).map(|_| to_key(&real_root, path)));
        let written_physically = physical_key
            .as_ref()
            .is_some_and(|key| written.contains(key));
        if trace.read_before_write.contains(lex)
            || physical
                .as_ref()
                .is_some_and(|path| trace.read_before_write.contains(path))
        {
            // A pre-write identity cannot be compared to the output after the run. Its verified
            // prior is recorded as an input instead.
            continue;
        }
        let external_written_physically = physical
            .as_deref()
            .is_some_and(|path| !path.starts_with(&real_root) && trace.is_output(path));
        if trace.is_output(lex) || written_physically || external_written_physically {
            let tracked_output = physical
                .as_deref()
                .map_or(inside || lex.starts_with(&real_root), |path| {
                    path.starts_with(&real_root)
                });
            if tracked_output
                && trace.seen.is_some()
                && touch.read
                && !verified_before_write
                && !trace.alias_read_targets.contains(lex)
            {
                refusals.push(NotRecorded::Other(format!(
                    "it read {key} and also wrote it"
                )));
            }
            continue;
        }
        if inside && key.split('/').any(|c| is_git_name(OsStr::new(c))) {
            reads_git = true;
            continue;
        }
        cands.push(Candidate {
            path: lex.clone(),
            key,
            inside,
            listed: touch.listed,
            physical_key: physical_key.filter(|_| inside),
            source: lex.clone(),
            followed: false,
        });
    }
    // A symlink hides a second file: record where it points, whether or not the link is ignored
    // (an alias under an ignored /tmp can point into the repository). The link must still resolve
    // to what it resolved to at the run's first look, or the file it read is no longer the one
    // recorded.
    for (lex, touch) in &trace.touched {
        if trace.magic_links.contains(lex) {
            continue;
        }
        // A link that was only written, not looked at, is an output rather than an input.
        if trace.is_output(lex) && (trace.seen.is_none() || !touch.read) {
            continue;
        }
        let first = trace.seen.as_ref().map(|seen| seen.get(lex));
        let link_key = to_key(root, lex);
        if ignore.is_ignored(&link_key) {
            // An ignored link matters only when it reached a tracked repository target. Retain
            // the first target as well as the current one, since the link may have moved.
            let first_target = first.and_then(|seen| match seen {
                Some(Seen::Symlink { resolved, .. }) => resolved.as_deref(),
                _ => None,
            });
            let current_target = std::fs::canonicalize(lex).ok();
            let mut tracked_target = false;
            for target in first_target.into_iter().chain(current_target.as_deref()) {
                if let Ok(rel) = target.strip_prefix(&real_root) {
                    if rel.to_str().is_none() {
                        return Err(
                            "it used a path in the repository that is not valid UTF-8".into()
                        );
                    }
                    let key = to_key(&real_root, target);
                    tracked_target |= !key.is_empty() && !ignore.is_ignored(&key);
                }
            }
            if !tracked_target {
                continue;
            }
        }
        if !std::fs::symlink_metadata(lex).is_ok_and(|m| m.file_type().is_symlink()) {
            // The run followed a link at its first look; no candidate checks what it resolved to now.
            if let Some(Some(Seen::Symlink {
                resolved: Some(_), ..
            })) = first
            {
                refusals.push(NotRecorded::Changed {
                    key: to_key(root, lex),
                });
            }
            continue;
        }
        // Proc magic links are resolved while the tracee is stopped. Resolving them here would
        // instead use the recorder's own process and working directory.
        if std::fs::read_link(lex)
            .is_ok_and(|target| target.starts_with("/proc") || target.starts_with("/dev/fd"))
        {
            continue;
        }
        let now = std::fs::canonicalize(lex).ok();
        match first {
            None => {}
            Some(None) => {
                refusals.push(NotRecorded::Other(format!(
                    "{} has no read-time identity",
                    to_key(root, lex)
                )));
                continue;
            }
            Some(Some(Seen::Symlink {
                target: original,
                followed,
                resolved: None,
            })) if !touch.content
                && matches!(followed.as_ref(), Seen::Absent)
                && std::fs::read_link(lex)
                    .is_ok_and(|target| target.as_os_str() == original.as_os_str())
                && now.as_deref().is_some_and(|target| {
                    trace.landed.contains(target)
                        && trace.keys.contains_key(target)
                        && (!trace.touched.get(target).is_some_and(|touch| touch.read)
                            || trace.read_before_write.contains(target))
                }) =>
            {
                // The dangling target was the verified output of this run. The link text is
                // checked as an input, and any earlier target lookup is kept as its prior input.
                continue;
            }
            Some(Some(Seen::Symlink { resolved, .. })) if *resolved == now => {}
            Some(Some(_)) => {
                refusals.push(NotRecorded::Changed {
                    key: to_key(root, lex),
                });
                continue;
            }
        }
        let target = match first {
            Some(Some(Seen::Symlink {
                resolved: Some(first_target),
                ..
            })) => first_target.clone(),
            _ => match now {
                Some(now) => now,
                None => continue,
            },
        };
        if target == real_root {
            continue;
        }
        match target.strip_prefix(&real_root) {
            Ok(rel) if !rel.as_os_str().is_empty() => {
                if rel.to_str().is_none() {
                    return Err("it used a path in the repository that is not valid UTF-8".into());
                }
                let tkey = to_key(&real_root, &target);
                if rel.components().any(|c| is_git_name(c.as_os_str())) {
                    if !ignore.is_ignored(&tkey) {
                        reads_git = true;
                    }
                    continue;
                }
                if ignore.is_ignored(&tkey) {
                    continue;
                }
                if trace.read_before_write.contains(&target) {
                    // The target's pre-write identity becomes an input below; still check the
                    // link itself and its resolution above.
                    continue;
                }
                if written.contains(&tkey) {
                    if trace.seen.is_some() && touch.read {
                        let why = format!("it read {tkey} through {link_key} and also wrote it");
                        if trace.alias_readbacks.contains(lex) {
                            // Stored, not refused: the run read what it wrote through a name it does
                            // not own. The record is unplannable, and no skip reuses it.
                            reasons.push(why);
                        } else {
                            refusals.push(NotRecorded::Other(why));
                        }
                    }
                    continue;
                }
                cands.push(Candidate {
                    path: target.clone(),
                    key: tkey.clone(),
                    inside: true,
                    listed: false,
                    physical_key: Some(tkey),
                    source: lex.clone(),
                    followed: true,
                });
            }
            _ => {
                if target
                    .strip_prefix(root)
                    .unwrap_or(&target)
                    .to_str()
                    .is_none()
                {
                    return Err("a symlink target is not valid UTF-8".into());
                }
                if trace.read_before_write.contains(&target) {
                    continue;
                }
                // External writes are untracked outputs, even when reached through a link.
                if trace.is_output(&target) {
                    continue;
                }
                let tk = to_key(root, &target);
                if ignore.is_ignored(&link_key) || ignore.is_ignored(&tk) {
                    continue;
                }
                cands.push(Candidate {
                    path: target.clone(),
                    key: tk,
                    inside: false,
                    listed: false,
                    physical_key: None,
                    source: lex.clone(),
                    followed: true,
                });
            }
        }
    }
    // Observations from ignored paths are retained for resolving aliases, but only a change that
    // contributes a recordable candidate can invalidate the record.
    for cand in &cands {
        if trace.changed_during.contains(&cand.source) || trace.changed_during.contains(&cand.path)
        {
            refusals.push(NotRecorded::Changed {
                key: cand.key.clone(),
            });
        }
    }
    if reads_git {
        return Err("it reads .git, so a skip could hide a history change (add `.git` to .stoopignore if that read cannot change the result)".into());
    }
    // All known paths share the snapshot taken before the command started. A changed attribute
    // source makes both its OIDs and its evidence stale.
    let epoch = trace
        .oid_epoch
        .as_deref()
        .filter(|_| !trace.oid_attrs_changed);
    // Tests also build synthetic traces without starting a traced command.
    #[cfg(test)]
    let synthetic_epoch =
        if epoch.is_none() && !trace.oid_epoch_captured && !trace.oid_attrs_changed {
            crate::oid_attrs::snapshot(&real_root)
        } else {
            None
        };
    #[cfg(test)]
    let epoch = epoch.or(synthetic_epoch.as_ref());
    let ids = par_map(&cands, |cand| {
        let basis = cand
            .physical_key
            .as_ref()
            .and_then(|physical| epoch.and_then(|epoch| epoch.basis.get(physical)));
        // A Git OID names the blob at the input's own tree path. A read reached through another
        // spelling (a directory alias) keeps its evidence but claims no OID.
        let names_tree_path = cand.physical_key.as_deref() == Some(cand.key.as_str());
        let with_oid = names_tree_path && basis.is_some_and(|basis| basis.allows_oid());
        let (id, post) = identify_post(&cand.path, cand.inside, cand.listed, with_oid);
        let checked = check_candidate(trace, cand, &post);
        let id = id.map(|(id, oid)| {
            // Evidence describes a file's attributes even when conversion or a length-changing read
            // prevents a raw Git OID from being emitted.
            let oid_basis = (id.starts_with("f:") || id.starts_with("x:"))
                .then(|| basis.cloned())
                .flatten();
            (id, oid, oid_basis)
        });
        (id, checked)
    });
    let mut out: Vec<Input> = Vec::with_capacity(cands.len() + trace.read_before_write.len());
    let mut keys: HashSet<String> = HashSet::new();
    for path in &trace.read_before_write {
        let Some(relative) = phys.repo_rel(path) else {
            return Err(NotRecorded::Other(format!(
                "it could not record the prior input {}",
                path.display()
            )));
        };
        if relative.to_str().is_none() {
            return Err("it used a path in the repository that is not valid UTF-8".into());
        }
        let key = to_key(&real_root, path);
        if ignore.is_ignored(&key) {
            continue;
        }
        if trace.changed_during.contains(path) {
            return Err(NotRecorded::Changed { key });
        }
        let Some(id) = trace.priors.get(&key) else {
            return Err(NotRecorded::Other(format!(
                "it could not verify what {key} held before writing it"
            )));
        };
        if trace.absent_after_removal.contains(path)
            && !matches!(identity::observe(path, false), Seen::Absent)
        {
            return Err(NotRecorded::Changed { key });
        }
        keys.insert(key.clone());
        out.push(Input {
            path: key,
            id: id.clone(),
            oid: None,
            oid_basis: None,
        });
    }
    for (cand, (id, checked)) in cands.iter().zip(ids) {
        if let Err(refusal) = checked {
            refusals.push(refusal);
        }
        if let Some((id, oid, oid_basis)) = id {
            if keys.insert(cand.key.clone()) {
                out.push(Input {
                    path: cand.key.clone(),
                    id,
                    oid,
                    oid_basis,
                });
            }
        }
    }
    if let Some(refusal) = refusals
        .into_iter()
        .min_by(|a, b| a.sort_key().cmp(b.sort_key()))
    {
        return Err(refusal);
    }
    out.sort_by(|a, b| a.path.cmp(&b.path));
    Ok((out, reasons))
}

