pub const ID_TOKEN_VARS: [&str; 2] = [
    "ACTIONS_ID_TOKEN_REQUEST_URL",
    "ACTIONS_ID_TOKEN_REQUEST_TOKEN",
];
static ID_TOKEN_ENV: OnceLock<[Option<OsString>; 2]> = OnceLock::new();

/// Called before any thread or child exists. The journal retains the values,
/// but every subprocess inherits an environment without them.
pub fn capture_id_token_env() {
    let values = ID_TOKEN_VARS.map(std::env::var_os);
    let _ = ID_TOKEN_ENV.set(values);
    for name in ID_TOKEN_VARS {
        while std::env::var_os(name).is_some() {
            std::env::remove_var(name);
        }
    }
}

pub fn id_token_value(name: &str) -> Option<OsString> {
    let index = ID_TOKEN_VARS
        .iter()
        .position(|candidate| *candidate == name)?;
    match ID_TOKEN_ENV.get() {
        Some(values) => values[index].clone(),
        None => std::env::var_os(name),
    }
}

pub fn id_token_string(name: &str) -> Option<String> {
    id_token_value(name)
        .and_then(|value| value.into_string().ok())
        .filter(|value| !value.trim().is_empty())
}

pub fn parse_pass_env(raw: Option<&OsStr>, allow: bool) -> Result<Vec<&'static str>, String> {
    let Some(raw) = raw else {
        return Ok(Vec::new());
    };
    let raw = raw.to_str().ok_or("STOOP_PASS_ENV must be UTF-8")?;
    let mut names = Vec::new();
    for name in raw
        .split(|ch: char| ch == ',' || ch.is_whitespace())
        .filter(|name| !name.is_empty())
    {
        let name = ID_TOKEN_VARS
            .iter()
            .copied()
            .find(|known| *known == name)
            .ok_or("STOOP_PASS_ENV may list only the two OIDC request variable names")?;
        if !allow {
            return Err(
                "STOOP_PASS_ENV requires --allow-id-token for OIDC request variables".into(),
            );
        }
        if !names.contains(&name) {
            names.push(name);
        }
    }
    Ok(names)
}

/// Nearest ancestor holding a `.git`, else the working directory.
pub fn find_root(cwd: &Path) -> PathBuf {
    let mut d = cwd;
    loop {
        if d.join(".git").exists() {
            return d.to_path_buf();
        }
        match d.parent() {
            Some(p) => d = p,
            None => return cwd.to_path_buf(),
        }
    }
}

/// Resolve an explicit root through symlinks, just like the process working directory.
pub fn root_for(o: &Opts, cwd: &Path) -> PathBuf {
    match &o.root {
        Some(root) => {
            let path = if root.is_absolute() {
                root.clone()
            } else {
                cwd.join(root)
            };
            std::fs::canonicalize(&path).unwrap_or_else(|_| absolutize(cwd, root))
        }
        None => find_root(cwd),
    }
}

pub fn store_for(o: &Opts, cwd: &Path, root: &Path) -> PathBuf {
    let path = o
        .store
        .clone()
        .or_else(|| env_str("STOOP_STORE").map(PathBuf::from))
        .unwrap_or_else(|| root.join(".stoop"));
    canonical_path(&absolutize(cwd, &path))
}

/// The path with symlinks resolved. A path that does not exist yet resolves through its parent,
/// so the same store has the same path before and after its first run.
fn canonical_path(path: &Path) -> PathBuf {
    if let Ok(resolved) = std::fs::canonicalize(path) {
        return resolved;
    }
    match (path.parent(), path.file_name()) {
        (Some(parent), Some(name)) => match std::fs::canonicalize(parent) {
            Ok(parent) => parent.join(name),
            Err(_) => path.to_path_buf(),
        },
        _ => path.to_path_buf(),
    }
}

/// Scope a shared store to a repository. A configured origin identifies checkouts
/// of the same repository; without one the physical root is the safe fallback.
pub(crate) fn shared_scope(root: &Path, store: &Path) -> Option<String> {
    if store == root.join(".stoop") {
        return None;
    }
    let remote = root
        .join(".git")
        .exists()
        .then(|| {
            Command::new("git")
                .arg("-C")
                .arg(root)
                .args(["config", "--local", "--get", "remote.origin.url"])
                .env_remove("GIT_DIR")
                .env_remove("GIT_WORK_TREE")
                .env_remove("GIT_COMMON_DIR")
                .output()
                .ok()
                .filter(|out| out.status.success())
                .and_then(|out| String::from_utf8(out.stdout).ok())
                .map(|url| url.trim().to_string())
                .filter(|url| !url.is_empty())
        })
        .flatten();
    let mut h = blake3::Hasher::new();
    if let Some(remote) = remote {
        h.update(b"remote\0");
        let path = Path::new(&remote);
        if !remote.contains(':') {
            let path = if path.is_absolute() {
                path.to_path_buf()
            } else {
                root.join(path)
            };
            let path = std::fs::canonicalize(&path).unwrap_or_else(|_| absolutize(root, &path));
            h.update(path.as_os_str().as_encoded_bytes());
        } else {
            h.update(remote.as_bytes());
        }
    } else {
        h.update(b"root\0");
        h.update(root.as_os_str().as_encoded_bytes());
    }
    Some(h.finalize().to_hex().to_string())
}

/// The words a hook record can hold: a record stores text, so only an argv of UTF-8 words is
/// recordable. The hook template is never recorded, so a shell-erased form of it is not recognised.
fn recordable_argv(words: &[std::ffi::OsString]) -> Option<Vec<String>> {
    words
        .iter()
        .map(|word| word.to_str().map(str::to_owned))
        .collect()
}

fn default_key(argv: &[std::ffi::OsString], rel_cwd: &str, scope: Option<&str>) -> String {
    let mut h = blake3::Hasher::new();
    for a in argv {
        h.update(a.as_encoded_bytes());
        h.update(&[0]);
    }
    h.update(rel_cwd.as_bytes());
    if let Some(scope) = scope {
        h.update(&[0]);
        h.update(scope.as_bytes());
    }
    let base = Path::new(&argv[0])
        .file_name()
        .map(|s| s.to_string_lossy().into_owned())
        .unwrap_or_else(|| "cmd".into());
    format!("{}-{}", sanitize(&base), &h.finalize().to_hex()[..16])
}

fn hook_key_with_config(
    hook: &units::hook::Hook,
    label: Option<&str>,
    cwd: &str,
    scope: Option<&str>,
    config_source: Option<&[u8]>,
    config_invalid: bool,
) -> String {
    let mut hash = blake3::Hasher::new();
    hash.update(b"stoop-hook-v1\0");
    for words in [&hook.original, &hook.argv] {
        hash.update(&(words.len() as u64).to_le_bytes());
        for word in words {
            let bytes = word.as_encoded_bytes();
            hash.update(&(bytes.len() as u64).to_le_bytes());
            hash.update(bytes);
        }
    }
    for value in [cwd, scope.unwrap_or(""), label.unwrap_or("")] {
        hash.update(&(value.len() as u64).to_le_bytes());
        hash.update(value.as_bytes());
    }
    if config_invalid {
        hash.update(b"\0stoop-config-invalid\0");
    } else if let Some(source) = config_source {
        hash.update(b"\0stoop-config-v1\0");
        hash.update(&(source.len() as u64).to_le_bytes());
        hash.update(source);
    }
    let base = label.unwrap_or_else(|| {
        Path::new(&hook.original[0])
            .file_name()
            .and_then(|s| s.to_str())
            .unwrap_or("cmd")
    });
    format!(
        "hook-{}-{}",
        sanitize(base),
        &hash.finalize().to_hex()[..16]
    )
}

#[cfg(all(test, unix))]
fn hook_key(
    hook: &units::hook::Hook,
    label: Option<&str>,
    cwd: &str,
    scope: Option<&str>,
) -> String {
    hook_key_with_config(hook, label, cwd, scope, None, false)
}

/// The environment counts as an input, because a variable read never shows up in
/// a file trace. The runner's own per-run bookkeeping is exempt unless the command
/// text names it, as are variables that differ on every start of the same machine.
pub fn ambient_env(mention: &str, ignore: &[String]) -> Vec<String> {
    const NOISY_PREFIX: &[&str] = &["GITHUB_", "RUNNER_", "ACTIONS_", "INPUT_", "STOOP_"];
    const ALWAYS_SKIP: &[&str] = &[
        "_",
        "PWD",
        "OLDPWD",
        "SHLVL",
        "TERM",
        "HOSTNAME",
        "INVOCATION_ID",
        "JOURNAL_STREAM",
        "SSH_AUTH_SOCK",
        "XDG_RUNTIME_DIR",
    ];
    // A name that is not UTF-8 is fingerprinted by its exact bytes (see `env_key`), so a change to
    // its value invalidates a proof like any other name. The ignore list and the skip list are
    // text, so they match by key and by the name's bytes.
    let mut names: Vec<String> = std::env::vars_os()
        .filter_map(|(name, _)| {
            let key = env_key(&name);
            let bytes = name.as_encoded_bytes();
            if ALWAYS_SKIP.iter().any(|skip| bytes == skip.as_bytes()) || ignore.contains(&key) {
                return None;
            }
            let noisy = NOISY_PREFIX.iter().any(|p| bytes.starts_with(p.as_bytes()));
            // The command text is text, so a name that is not UTF-8 is matched in lossy form.
            (!noisy || mention.contains(name.to_string_lossy().as_ref())).then_some(key)
        })
        .collect();
    names.sort();
    names
}

/// The fingerprint key of an environment name. A UTF-8 name is its own key. A name that is not
/// UTF-8 is a NUL followed by its bytes in hex. An environment name cannot hold NUL, so no UTF-8
/// name collides with such a key, and `env_name` reverses it exactly.
pub fn env_key(name: &std::ffi::OsStr) -> String {
    match name.to_str() {
        Some(text) => text.to_string(),
        None => {
            let mut key = String::from("\u{0}");
            for byte in name.as_encoded_bytes() {
                key.push_str(&format!("{byte:02x}"));
            }
            key
        }
    }
}

/// The environment name a fingerprint key stands for: the exact inverse of `env_key`.
pub fn env_name(key: &str) -> std::ffi::OsString {
    let Some(hex) = key.strip_prefix('\u{0}') else {
        return std::ffi::OsString::from(key);
    };
    let bytes: Option<Vec<u8>> = (0..hex.len())
        .step_by(2)
        .map(|i| {
            hex.get(i..i + 2)
                .and_then(|pair| u8::from_str_radix(pair, 16).ok())
        })
        .collect();
    match bytes {
        #[cfg(unix)]
        Some(bytes) => {
            use std::os::unix::ffi::OsStringExt;
            std::ffi::OsString::from_vec(bytes)
        }
        // Windows names are UTF-16. A name that was not valid Unicode cannot be rebuilt from
        // its key, so it stays as the key text.
        #[cfg(windows)]
        Some(bytes) => match String::from_utf8(bytes) {
            Ok(text) => std::ffi::OsString::from(text),
            Err(_) => std::ffi::OsString::from(key),
        },
        None => std::ffi::OsString::from(key),
    }
}

/// Run each probe and hash what it prints. `None` if any fails: an external fact that
/// could not be established is never assumed unchanged.
pub fn run_probes(probes: &[String], cwd: &Path, quiet: bool) -> Option<BTreeMap<String, String>> {
    let mut out = BTreeMap::new();
    for p in probes {
        let res = Command::new("sh")
            .arg("-c")
            .arg(p)
            .current_dir(cwd)
            .stdin(Stdio::null())
            .stderr(Stdio::null())
            .output();
        match res {
            Ok(o) if o.status.success() => {
                out.insert(p.clone(), blake3::hash(&o.stdout).to_hex().to_string());
            }
            Ok(o) => {
                if !quiet {
                    eprintln!("stoop: probe `{p}` failed ({})", o.status);
                }
                return None;
            }
            Err(e) => {
                if !quiet {
                    eprintln!("stoop: cannot run probe `{p}`: {e}");
                }
                return None;
            }
        }
    }
    Some(out)
}

/// A secret that keys the environment hashes stored in proofs. Proofs published to a
/// git remote are readable by anyone who can read the repository, and an unsalted hash
/// of a low-entropy value (a short token, a boolean flag) can be guessed offline. With
/// the salt set, hashes are keyed with it and carry the `s:` prefix; whoever checks a
/// proof needs the same salt, so runs without the secret (fork pull requests) simply
/// cannot match and the command runs. The salt itself is never hashed in.
pub const SALT_VAR: &str = "STOOP_ENV_SALT";

pub fn env_hash(name: &str, value: &str, salt: Option<&[u8]>) -> String {
    env_hash_bytes(name, value.as_bytes(), salt)
}

/// `env_hash` for a value that may not be UTF-8: the exact bytes are hashed.
pub fn env_hash_bytes(name: &str, value: &[u8], salt: Option<&[u8]>) -> String {
    match salt {
        Some(salt) => {
            let key = blake3::derive_key("stoop env hash v1", salt);
            let mut h = blake3::Hasher::new_keyed(&key);
            h.update(name.as_bytes());
            h.update(&[0]);
            h.update(value);
            format!("s:{}", h.finalize().to_hex())
        }
        None => blake3::hash(value).to_hex().to_string(),
    }
}

fn env_hashes(names: &[String], salt: Option<&[u8]>) -> BTreeMap<String, String> {
    names
        .iter()
        .map(|n| {
            let value = std::env::var_os(env_name(n)).unwrap_or_default();
            (n.clone(), env_hash_bytes(n, value.as_encoded_bytes(), salt))
        })
        .collect()
}

/// A proof stops counting after this long. It bounds what a file trace cannot see
/// (the clock above all): a test that depends on today's date is wrong for at most this long.
pub const DEFAULT_MAX_AGE: u64 = 7 * 86_400;

/// An on/off environment switch. Empty, `0`, `false`, `no` and `off` are off. That
/// matters for the common CI idiom `X: ${{ cond && '1' || '' }}`, which sets the
/// variable to an empty string when the condition is false: merely being set must
/// not turn on something that publishes proofs.
pub fn env_flag(name: &str) -> bool {
    match std::env::var(name) {
        Ok(v) => {
            let v = v.trim().to_ascii_lowercase();
            !(v.is_empty() || matches!(v.as_str(), "0" | "false" | "no" | "off"))
        }
        Err(_) => false,
    }
}

/// An on/off switch stoop must not misread. A value that is not UTF-8 is not a switch it
/// recognises, so `unreadable_on` decides: `true` for a switch whose "on" only makes stoop
/// run more and skip less, `false` for a switch whose "on" publishes or stores more.
pub fn env_switch(name: &str, unreadable_on: bool) -> bool {
    match std::env::var_os(name) {
        Some(value) if value.to_str().is_none() => unreadable_on,
        _ => env_flag(name),
    }
}

/// A string environment variable; empty counts as unset.
pub fn env_str(name: &str) -> Option<String> {
    std::env::var(name).ok().filter(|v| !v.trim().is_empty())
}

/// The proof salt: the exact bytes of `STOOP_ENV_SALT`. A salt that is not UTF-8 still keys every
/// hash, so it can never fall back to the unsalted hashes a remote would publish. An empty or
/// blank salt is unset, as before.
pub fn env_salt() -> Option<Vec<u8>> {
    salt_from(SALT_VAR)
}

fn salt_from(name: &str) -> Option<Vec<u8>> {
    let value = std::env::var_os(name)?;
    let blank = value.to_str().is_some_and(|text| text.trim().is_empty());
    (!blank).then(|| value.into_encoded_bytes())
}

/// "90s", "30m", "12h", "7d", or a bare number of seconds. "0" means never expire.
pub fn parse_age(s: &str) -> Result<u64, String> {
    let s = s.trim();
    let (num, mult) = match s.chars().last() {
        Some('s') => (&s[..s.len() - 1], 1),
        Some('m') => (&s[..s.len() - 1], 60),
        Some('h') => (&s[..s.len() - 1], 3600),
        Some('d') => (&s[..s.len() - 1], 86_400),
        _ => (s, 1),
    };
    num.parse::<u64>()
        .ok()
        .and_then(|n| n.checked_mul(mult))
        .ok_or_else(|| format!("cannot read {s:?} as a duration (try 90s, 30m, 12h, 7d)"))
}

/// A path or probe name as explain prints it. Control characters become `\u{..}`, so a name cannot
/// start a line of its own on stderr, where the MCP server reads explain's lines.
fn shown_text(text: &str) -> String {
    let mut shown = String::with_capacity(text.len());
    for ch in text.chars() {
        if ch.is_control() {
            shown.push_str(&format!("\\u{{{:x}}}", ch as u32));
        } else {
            shown.push(ch);
        }
    }
    shown
}

fn ago(created: u64) -> String {
    let s = now().saturating_sub(created);
    match s {
        0..=89 => format!("{s}s ago"),
        90..=5399 => format!("{}m ago", s / 60),
        5400..=129_599 => format!("{}h ago", s / 3600),
        _ => format!("{}d ago", s / 86_400),
    }
}

fn plain(argv: &[std::ffi::OsString], pass_env: &[&str]) -> i32 {
    let mut command = std::process::Command::new(&argv[0]);
    command.args(&argv[1..]);
    for name in pass_env {
        if let Some(value) = id_token_value(name) {
            command.env(name, value);
        }
    }
    match command.status() {
        Ok(s) => crate::sys::exit_code(s),
        Err(e) => {
            eprintln!(
                "stoop: cannot run {}: {e}",
                safe(&argv[0].to_string_lossy())
            );
            127
        }
    }
}

/// The opt-in macOS diagnostic: run the command once under DTrace and report what it did. Nothing
/// is recorded, and the command's own status is returned. `None` means the tracer could not be
/// armed and the command has not run, so the caller runs it untraced as usual. The report prints
/// even under `--quiet`, because the variable asked for it.
#[cfg(target_os = "macos")]
fn dtrace_diagnostic(o: &Opts, cwd: &Path, key: &str) -> Option<Outcome> {
    let mode = env_str("STOOP_DTRACE_DIAGNOSTIC").unwrap_or_default();
    let raw = mode == "raw";
    let paths = raw || mode == "list";
    let diagnostic = match trace::macos::diagnose(&o.argv, cwd, raw) {
        Ok(diagnostic) => diagnostic,
        Err(e) => {
            eprintln!("stoop: DTrace diagnostic verdict: UNKNOWN ({e}); running untraced");
            return None;
        }
    };
    for line in trace::macos::report(&diagnostic, paths, raw) {
        eprintln!("stoop: {line}");
    }
    Some(Outcome {
        status: diagnostic.trace.status,
        key: key.to_owned(),
        how: diagnostic_how(diagnostic.trace.status),
    })
}

pub enum How {
    Skipped { proof: String },
    Recorded { proof: String },
    Unrecorded(String),
    Failed,
    Untraced,
}

pub struct Outcome {
    pub status: i32,
    pub key: String,
    pub how: How,
}

/// How a diagnostic run is journaled. It is never a proof: a command that failed is a failed step,
/// as it is when traced on Linux, and a command that passed is blocked, because nothing was
/// recorded.
#[cfg_attr(not(target_os = "macos"), allow(dead_code))]
pub(crate) fn diagnostic_how(status: i32) -> How {
    if status == 0 {
        How::Unrecorded("macOS DTrace diagnostic: never recorded".into())
    } else {
        How::Failed
    }
}

