fn hook_max_age(o: &Opts) -> u64 {
    o.max_age
        .or_else(|| {
            std::env::var("STOOP_MAX_AGE")
                .ok()
                .and_then(|v| parse_age(&v).ok())
        })
        .unwrap_or(DEFAULT_MAX_AGE)
}

type RecoveredHooks = Vec<(units::hook::Hook, String)>;

fn recover_hooks(
    o: &Opts,
    root: &Path,
    cwd: &str,
    store: &Path,
    scope: Option<&str>,
    max_age: u64,
) -> (Vec<String>, Result<RecoveredHooks, String>) {
    let mut warnings = Vec::new();
    let records = match units::hook_store::records(store, now(), max_age) {
        Ok(records) => records,
        Err(warning) => {
            if !o.quiet {
                warnings.push(warning);
            }
            return (warnings, Ok(Vec::new()));
        }
    };
    let mut found: Vec<(units::hook::Hook, String)> = Vec::new();
    let mut configured = false;
    for record in records.into_iter().filter(|record| {
        record.cwd == cwd && record.scope.as_deref() == scope && record.label == o.key
    }) {
        let words: Vec<OsString> = record.argv.into_iter().map(OsString::from).collect();
        let Ok(Some(parsed)) = units::hook::parse(&words) else {
            continue;
        };
        if !parsed.expanded_matches(&o.argv) {
            continue;
        }
        let (warning, prepared) = units::config::finish(root, cwd, &words, parsed);
        if let Some(warning) = warning {
            if !warnings.contains(&warning) {
                warnings.push(warning);
            }
        }
        match prepared {
            Ok(prepared) => {
                configured |= prepared.config.key_source().is_some();
                if prepared.invalid {
                    return (warnings, Err("the recorded hook has invalid configuration; quote the placeholder or use --literal".into()));
                }
                if let Some(candidate) = prepared.hook {
                    if hook_key_with_config(
                        &candidate,
                        record.label.as_deref(),
                        cwd,
                        scope,
                        prepared.config.key_source(),
                        prepared.invalid,
                    ) != record.key
                    {
                        return (warnings, Err("the recorded hook's full form changed; quote the placeholder or use --literal".into()));
                    }
                    if !found.iter().any(|(known, _)| known.argv == candidate.argv) {
                        found.push((candidate, record.key));
                    }
                }
            }
            Err(error) => return (warnings, Err(error)),
        }
    }
    if configured && found.len() > 1 {
        return (
            warnings,
            Err(
                "recorded hooks have different full forms; quote the placeholder or use --literal"
                    .into(),
            ),
        );
    }
    (warnings, Ok(found))
}

/// The error that stops a placeholder argv before anything runs, if there is one.
pub fn hook_refusal(o: &Opts) -> Option<String> {
    let cwd = std::env::current_dir().unwrap_or_else(|_| PathBuf::from("."));
    let root = root_for(o, &cwd);
    let rel_cwd = cwd_key(&root, &cwd);
    let (warning, prepared) = units::config::prepare(&root, &rel_cwd, &o.argv, o.literal);
    match prepared {
        Err(error) => {
            if let Some(warning) = warning {
                eprintln!("{warning}");
            }
            Some(error)
        }
        Ok(prepared) if prepared.hook.is_none() && !o.literal => {
            let store = store_for(o, &cwd, &root);
            let scope = shared_scope(&root, &store);
            let (warnings, recovered) = recover_hooks(
                o,
                &root,
                &rel_cwd,
                &store,
                scope.as_deref(),
                hook_max_age(o),
            );
            if let Err(error) = recovered {
                for warning in warnings {
                    eprintln!("{warning}");
                }
                Some(error)
            } else {
                None
            }
        }
        Ok(_) => None,
    }
}

/// The variables that carry a placeholder's value (spec section 4.7). Stoop owns them for each run.
pub(crate) const HOOK_ENV: [&str; 5] = [
    "STOOP_CHANGED",
    "STOOP_CHANGED_FILE",
    "STOOP_CHANGED_INPUTS",
    "STOOP_CHANGED_INPUTS_FILE",
    "STOOP_UNITS",
];

/// Set the hook variables for the child. A hook exports all of them, empty. Any other run only
/// replaces an inherited value, and names it unless `warn` is false.
fn clear_hook_env(hook: bool, warn: bool) {
    for name in HOOK_ENV {
        let inherited = std::env::var_os(name).is_some_and(|value| !value.is_empty());
        if inherited && warn {
            eprintln!("stoop: ignoring inherited {name}; the shell may already have expanded it");
        }
        if hook || std::env::var_os(name).is_some() {
            std::env::set_var(name, "");
        }
    }
}

/// Remove the hook records stored under one key. A damaged catalog is a warning.
pub fn forget_hook_records(o: &Opts, key: &str) -> Result<bool, String> {
    let cwd = std::env::current_dir().unwrap_or_else(|_| PathBuf::from("."));
    let root = root_for(o, &cwd);
    units::hook_store::forget(&store_for(o, &cwd, &root), key)
}

/// Forget what was learned about environment variables under `key`. Returns whether anything was.
pub fn forget_volatile(o: &Opts, key: &str) -> Result<bool, String> {
    let cwd = std::env::current_dir().unwrap_or_else(|_| PathBuf::from("."));
    let root = root_for(o, &cwd);
    volatile::forget(&store_for(o, &cwd, &root), key)
}

/// `stoop ls` lines for the names learned as bookkeeping under the current salt.
pub fn volatile_listing(o: &Opts) -> Result<Vec<String>, String> {
    let cwd = std::env::current_dir().unwrap_or_else(|_| PathBuf::from("."));
    let root = root_for(o, &cwd);
    let salt = env_salt();
    let learned = volatile::list(
        &store_for(o, &cwd, &root),
        &volatile::salt_id(salt.as_deref()),
    )?;
    let mut lines = Vec::new();
    for (key, names) in learned {
        for (name, runs) in names {
            lines.push(format!(
                "volatile\t{key}\tignores {}\tlearned after {runs} runs",
                volatile::safe(&name)
            ));
        }
    }
    Ok(lines)
}

/// Learning is on unless `--no-learn-volatile` or `STOOP_LEARN_VOLATILE` turns it off. An empty,
/// `0`, `false`, `no` or `off` value is off. A value that is not UTF-8 is off as well: a run that
/// does not learn counts more, so it skips less.
pub fn learning_on(o: &Opts) -> bool {
    if o.no_learn_volatile {
        return false;
    }
    match std::env::var_os("STOOP_LEARN_VOLATILE") {
        None => true,
        Some(value) => match value.to_str() {
            Some(text) => !matches!(
                text.trim().to_ascii_lowercase().as_str(),
                "" | "0" | "false" | "no" | "off"
            ),
            None => false,
        },
    }
}

pub(crate) struct RunCx<'a> {
    pub(crate) o: &'a Opts,
    pub(crate) cwd: &'a PathBuf,
    pub(crate) root: &'a PathBuf,
    pub(crate) rel_cwd: &'a String,
    scope: &'a Option<String>,
    store: &'a Store,
    pub(crate) hook: &'a Option<units::hook::Hook>,
    pub(crate) full_reason: &'a Option<String>,
    max_age: u64,
    bypass: bool,
    explain: bool,
    observe_runners: bool,
    pub(crate) env_now: BTreeMap<String, String>,
    pub(crate) env_excluded: Vec<String>,
    salt: &'a Option<Vec<u8>>,
    remote: Option<Remote>,
}

/// Why the options keep a hooked command from an attribution pass (spec 3.1), if they do. They also
/// govern the later unit-execution path. Explain asks the same question, so this does not look at
/// explain itself. `STOOP_OFF` is not here: `screen` names it before any other refusal.
fn units_refusal(
    cx: &RunCx<'_>,
    config_invalid: bool,
    independent_false: bool,
) -> Option<units::attribution::Refusal> {
    let o = cx.o;
    let allowed = cx.hook.is_some()
        && !cx.bypass
        && cx.observe_runners
        && !config_invalid
        && !independent_false
        && !o.no_record
        && !o.allow_network
        && o.probes.is_empty()
        && o.ignore.is_empty()
        && o.ignore_env.is_empty();
    (!allowed).then_some(units::attribution::Refusal::Options)
}

/// The suite a hooked command names: its filter, the roster discovery finds for it, and the record
/// a pass would write for that roster. `None` when the command names no filter or the tree cannot be
/// read. A run passes no refusal, because it asks only when the options allow units. Explain passes
/// the refusal it found, and reports it through the record.
fn unit_suite(
    cx: &RunCx<'_>,
    config: &units::config::Config,
    refusal: Option<units::attribution::Refusal>,
) -> Option<units::attribution::Suite> {
    let hook = cx.hook.as_ref()?;
    let suite = config.select(&hook.original, cx.rel_cwd).ok().flatten();
    let configured = suite
        .and_then(|suite| suite.units.as_ref())
        .map(|patterns| units::filter::Filter::configured(patterns));
    let inline = (!hook.shell_env_code)
        .then(|| {
            hook.placeholders
                .iter()
                .flatten()
                .find_map(|placeholder| placeholder.filter.as_ref())
        })
        .flatten();
    let filter = inline.or(configured.as_ref())?;
    let ignore = units::universe::catalog_ignore(cx.root, &cx.o.ignore, &cx.o.transient).ok()?;
    let catalog = units::universe::discover(cx.root, &ignore, filter, configured.as_ref()).ok()?;
    let roster: Vec<String> = catalog.units.into_iter().map(|unit| unit.0).collect();
    let id = units::bundle::suite_id(
        &hook.original,
        cx.rel_cwd,
        cx.scope.as_deref(),
        cx.o.key.as_deref(),
    );
    let pending = match refusal {
        Some(refusal) => Err(refusal),
        None => units::bundle::pending(units::bundle::PendingSpec {
            argv: &hook.original,
            cwd: cx.rel_cwd,
            scope: cx.scope.as_deref(),
            label: cx.o.key.as_deref(),
            source: if inline.is_some() { "filter" } else { "config" },
            filter: filter.text(),
            units: roster.clone(),
            config: config.key_source(),
            config_suite: suite.map(|suite| suite.id.as_str()),
        }),
    };
    Some(units::attribution::Suite {
        id,
        units: roster,
        pending,
    })
}

fn unit_bookkeeping(
    cx: &RunCx<'_>,
    config: &units::config::Config,
    config_invalid: bool,
    independent_false: bool,
) -> Option<units::bundle::Pending> {
    if cx.explain || units_refusal(cx, config_invalid, independent_false).is_some() {
        return None;
    }
    unit_suite(cx, config, None)?.pending.ok()
}

pub(crate) struct Lookup {
    pub(crate) proofs: Vec<Proof>,
    pub(crate) hit_idx: Option<usize>,
    why: String,
    t0: Instant,
}

fn run_internal(mut o: Opts, explain: bool, observe_runners: bool) -> Outcome {
    let initial_key = o.key.clone().unwrap_or_default();
    if o.argv.is_empty() {
        eprintln!("stoop: no command given");
        return Outcome {
            status: 2,
            key: initial_key,
            how: How::Untraced,
        };
    }
    if !o.pass_env.is_empty() {
        if explain {
            if !o.quiet {
                eprintln!("stoop: would run without a proof: OIDC request credentials are explicitly passed");
            }
            return Outcome {
                status: 1,
                key: initial_key,
                how: How::Unrecorded("OIDC request credentials passed".into()),
            };
        }
        if !o.quiet {
            eprintln!("stoop: running untraced without a proof: OIDC request credentials are explicitly passed");
        }
        return Outcome {
            status: plain(&o.argv, &o.pass_env),
            key: initial_key,
            how: How::Unrecorded("OIDC request credentials passed".into()),
        };
    }
    let cwd = std::env::current_dir().unwrap_or_else(|_| PathBuf::from("."));
    let root = root_for(&o, &cwd);
    let rel_cwd = cwd_key(&root, &cwd);
    let store_path = store_for(&o, &cwd, &root);
    let scope = shared_scope(&root, &store_path);
    let literal = o.literal || !observe_runners;
    let (warning, prepared) = units::config::prepare(&root, &rel_cwd, &o.argv, literal);
    if let Some(warning) = warning {
        eprintln!("{warning}");
    }
    let units::config::Prepared {
        mut hook,
        config,
        invalid: config_invalid,
        independent_false,
    } = match prepared {
        Ok(prepared) => prepared,
        Err(error) => {
            eprintln!("stoop: {error}");
            return Outcome {
                status: 2,
                key: initial_key,
                how: How::Untraced,
            };
        }
    };
    // A placeholder that reached stoop intact: the shell expanded nothing into it.
    let intact = hook.is_some();
    if let Some(h) = &hook {
        o.argv.clone_from(&h.argv);
    }
    let max_age = hook_max_age(&o);
    // An erased hook runs its recorded full form and never skips. Configured conflicting
    // forms, invalid configuration, or changed configuration identity are refused.
    let mut expanded = false;
    let mut recovered_key = None;
    let mut matches = 0;
    if !literal && hook.is_none() {
        let (warnings, recovered) =
            recover_hooks(&o, &root, &rel_cwd, &store_path, scope.as_deref(), max_age);
        for warning in warnings {
            eprintln!("{warning}");
        }
        let mut found = match recovered {
            Ok(found) => found,
            Err(error) => {
                eprintln!("stoop: {error}");
                return Outcome {
                    status: 2,
                    key: initial_key,
                    how: How::Untraced,
                };
            }
        };
        matches = found.len();
        if matches == 1 {
            let (candidate, key) = found.swap_remove(0);
            recovered_key = Some(key);
            o.argv.clone_from(&candidate.argv);
            hook = Some(candidate);
            expanded = true;
        }
    }
    let bypass = expanded || matches > 1;
    // Stoop owns the hook variables for its child. A hook exports them empty. Any other run
    // replaces an inherited value and names it, unless a placeholder reached stoop intact.
    if !literal {
        clear_hook_env(hook.is_some(), !intact);
    }
    let key = recovered_key
        .or_else(|| {
            hook.as_ref().map(|h| {
                hook_key_with_config(
                    h,
                    o.key.as_deref(),
                    &rel_cwd,
                    scope.as_deref(),
                    config.key_source(),
                    config_invalid,
                )
            })
        })
        .unwrap_or_else(|| {
            o.key
                .as_deref()
                .map(|key| {
                    if o.shell_key {
                        crate::stepkey::scoped(key, scope.as_deref())
                    } else {
                        sanitize(key)
                    }
                })
                .unwrap_or_else(|| default_key(&o.argv, &rel_cwd, scope.as_deref()))
        });
    // One decision line for an expanded shape, an ambiguous shape or an empty value. Explain
    // prints it in place of the run and runs nothing; a run prints it as its hint.
    let note = if expanded {
        hook.as_ref().map(|h| {
            if explain {
                units::hook::expanded_explain(h)
            } else {
                units::hook::expanded_line(h)
            }
        })
    } else if matches > 1 {
        Some(units::hook::ambiguous_line(&o.argv, matches, explain))
    } else if !literal && hook.is_none() {
        units::hook::empty_value_line(&o.argv, explain)
    } else {
        None
    };
    if let Some(line) = note {
        eprintln!("{line}");
        if explain {
            return Outcome {
                status: 1,
                key,
                how: How::Untraced,
            };
        }
    }
    if let Some(h) = &hook {
        if !expanded && !explain && !o.no_record {
            // A record holds text. A hook template with an argument that is not UTF-8 is not
            // recorded, so a shell-erased form of this hook is not recognised. The whole-command
            // proof is keyed by the exact bytes and is still recorded.
            let words = recordable_argv(&h.original);
            match words {
                Some(argv) => {
                    let record = units::hook_store::Record {
                        key: key.clone(),
                        argv,
                        cwd: rel_cwd.clone(),
                        scope: scope.clone(),
                        label: o.key.clone(),
                        created: now(),
                    };
                    if let Err(warning) = units::hook_store::record(&store_path, record) {
                        if !o.quiet {
                            eprintln!("{warning}");
                        }
                    }
                }
                None if !o.quiet => {
                    eprintln!(
                        "stoop: the hook template is not recorded, so a shell-erased form of this hook will not be recognised"
                    );
                }
                None => {}
            }
        }
    }
    // STOOP_OFF runs a hook's first-run form without tracing, and its hints still print above.
    if env_switch("STOOP_OFF", true) && !explain {
        return Outcome {
            status: plain(&o.argv, &[]),
            key: initial_key,
            how: How::Untraced,
        };
    }
    let volatile_store = store_path.clone();
    let store = Store::new(store_path);
    if explain && !o.quiet {
        let dir = if rel_cwd.is_empty() { "." } else { &rel_cwd };
        eprintln!("stoop: dir {dir:?}");
        if let Some(hook) = &hook {
            if hook.shell_env_code {
                eprintln!("stoop: shell-operand filters are unavailable; use a quoted argv placeholder such as '{{changed:/foo}}'");
            }
            let suite = config.select(&hook.original, &rel_cwd).ok().flatten();
            let configured = suite.and_then(|suite| {
                suite.units.as_ref().map(|patterns| {
                    (
                        units::filter::Filter::configured(patterns),
                        suite.id.as_str(),
                    )
                })
            });
            let inline = hook
                .placeholders
                .iter()
                .flatten()
                .find_map(|placeholder| placeholder.filter.as_ref());
            match units::universe::catalog_ignore(&root, &o.ignore, &o.transient) {
                Ok(ignore) => eprintln!(
                    "{}",
                    units::universe::explain(
                        &root,
                        &ignore,
                        inline,
                        configured.as_ref().map(|(filter, id)| (filter, *id)),
                    )
                ),
                Err(reason) => eprintln!("stoop: no unit universe: {}", units::hook::safe(&reason)),
            }
        }
    }
    if !trace::supported() {
        if explain {
            match &hook {
                Some(h) => eprintln!(
                    "stoop: would run full {key} (not traced: {}): removed {}, argv {}",
                    trace::UNAVAILABLE,
                    units::hook::show(&h.removed),
                    units::hook::render(&h.argv)
                ),
                None => eprintln!(
                    "stoop: would run {key}: not traced ({}); no proof can be used",
                    trace::UNAVAILABLE
                ),
            }
            return Outcome {
                status: 1,
                key,
                how: How::Untraced,
            };
        }
        #[cfg(target_os = "macos")]
        if env_switch("STOOP_DTRACE_DIAGNOSTIC", false) {
            if let Some(outcome) = dtrace_diagnostic(&o, &cwd, &key) {
                return outcome;
            }
        }
        if !o.quiet {
            match &hook {
                Some(h) => eprintln!(
                    "stoop: run full {key} (no compatible tracer): removed {}",
                    units::hook::show(&h.removed)
                ),
                None => eprintln!("stoop: run {key}: no compatible tracer"),
            }
            eprintln!(
                "stoop: not traced ({}); running without a proof",
                trace::UNAVAILABLE
            );
        }
        return Outcome {
            status: plain(&o.argv, &[]),
            key,
            how: How::Untraced,
        };
    }
    let full_reason = if env_switch("STOOP_FULL", true) {
        Some("STOOP_FULL is set".to_string())
    } else if hook.is_some() && config_invalid {
        Some("invalid unit configuration".to_string())
    } else if hook.is_some() && independent_false {
        Some("suite is not independent".to_string())
    } else if hook.is_some() {
        let sync = o.sync.clone().or_else(|| env_str("STOOP_SYNC"));
        units::policy::forced_reason(
            &root,
            &config,
            sync.as_deref(),
            o.sync_write || env_flag("STOOP_SYNC_WRITE"),
        )
    } else {
        None
    };
    let max_age = o
        .max_age
        .or_else(|| {
            std::env::var("STOOP_MAX_AGE")
                .ok()
                .and_then(|v| parse_age(&v).ok())
        })
        .unwrap_or(DEFAULT_MAX_AGE);
    // The words are mentioned as lossy text: the names a command can mention are ASCII.
    let mention = format!(
        "{} {}",
        o.argv
            .iter()
            .map(|word| word.to_string_lossy())
            .collect::<Vec<_>>()
            .join(" "),
        o.mention
    );
    let candidates = ambient_env(&mention, &o.ignore_env);
    let salt = env_salt();
    let volatile = volatile::decide(&volatile::Request {
        store: &volatile_store,
        key: &key,
        candidates: &candidates,
        mention: &mention,
        forced: &o.env,
        ignore: &o.ignore_env,
        salt: salt.as_deref(),
        learn: learning_on(&o),
        // A run that does not write its record, or only explains, observes in memory: it must not
        // change what a trusted run has learned.
        persist: !explain && !o.no_record,
        now: now(),
    });
    for line in &volatile.changes {
        if !o.quiet {
            eprintln!("stoop: {line}");
        }
    }
    if let Some(warning) = &volatile.warning {
        if !o.quiet {
            eprintln!("{warning}");
        }
    }
    if explain && !o.quiet {
        for (name, why) in &volatile.plan.excluded {
            eprintln!("stoop: ignoring env {}: {why}", volatile::safe(name));
        }
    }
    let env_excluded: Vec<String> = volatile
        .plan
        .excluded
        .iter()
        .map(|(name, _)| name.clone())
        .collect();
    let env_now = env_hashes(&volatile.plan.counted, salt.as_deref());

    let remote = o
        .sync
        .clone()
        .or_else(|| env_str("STOOP_SYNC"))
        .and_then(|spec| {
            let write = o.sync_write || env_flag("STOOP_SYNC_WRITE");
            match Remote::from_spec(&spec, &root, write) {
                Ok(r) => Some(r),
                Err(e) => {
                    eprintln!("stoop: sync: {e}");
                    None
                }
            }
        });
    let cx = RunCx {
        o: &o,
        cwd: &cwd,
        root: &root,
        rel_cwd: &rel_cwd,
        scope: &scope,
        store: &store,
        hook: &hook,
        full_reason: &full_reason,
        max_age,
        bypass,
        explain,
        observe_runners,
        env_now,
        env_excluded,
        salt: &salt,
        remote,
    };
    let lookup = legacy_lookup(&cx, &key);
    // The roster is taken before the command launches. Only a run that launches takes it: a
    // whole-command hit that is skipped never walks the tree. This is the skip legacy_finish applies.
    let launches = cx.full_reason.is_some() || lookup.hit_idx.is_none();
    let pending = if launches {
        unit_bookkeeping(&cx, &config, config_invalid, independent_false)
    } else {
        None
    };
    // The one call that dispatches an attribution pass (spec 3.1). Removing this statement
    // returns every hooked run to the legacy path.
    if let Some(outcome) = pending.as_ref().and_then(|pending| {
        units::attribution::pass(&cx, &config, &lookup, pending, &volatile_store, &key)
    }) {
        return outcome;
    }
    // Explain adds two lines to a suite's decision (spec 4.16). They are computed while the context
    // is whole, and printed after the lines the legacy path prints.
    let suite_lines = (explain && !o.quiet)
        .then(|| {
            let refusal = units_refusal(&cx, config_invalid, independent_false);
            let suite = unit_suite(&cx, &config, refusal);
            units::attribution::explain_lines(
                &cx,
                &config,
                &lookup,
                suite.as_ref(),
                &volatile_store,
                &key,
            )
        })
        .flatten();
    let outcome = legacy_finish(cx, key, lookup);
    for line in suite_lines.into_iter().flatten() {
        eprintln!("{line}");
    }
    if let (Some(pending), How::Recorded { proof: digest }) = (pending, &outcome.how) {
        if let Some(proof) = store
            .load(&outcome.key)
            .into_iter()
            .find(|proof| proof.digest() == *digest)
        {
            units::bundle::record(&volatile_store, pending, &outcome.key, digest, proof);
        }
    }
    outcome
}

fn legacy_lookup(cx: &RunCx<'_>, key: &str) -> Lookup {
    let o = cx.o;
    let cwd = cx.cwd;
    let root = cx.root;
    let rel_cwd = cx.rel_cwd;
    let scope = cx.scope;
    let store = cx.store;
    let max_age = cx.max_age;
    let bypass = cx.bypass;
    let explain = cx.explain;
    let env_now = &cx.env_now;
    let env_excluded = &cx.env_excluded;
    let remote = &cx.remote;
    let excluded_now: std::collections::BTreeSet<&String> = env_excluded.iter().collect();

    // 1. Is there a proof whose inputs all still match?
    let t0 = Instant::now();
    let mut proofs = if bypass { Vec::new() } else { store.load(key) };
    let mut pulled = false;
    let mut probe_now: Option<Option<BTreeMap<String, String>>> = None;
    let mut why;
    let mut hit_idx: Option<usize>;
    loop {
        why = String::from("no proof yet");
        hit_idx = None;
        for (i, p) in proofs.iter().enumerate() {
            let expired = max_age > 0 && now().saturating_sub(p.created) > max_age;
            let diffs: Vec<(String, &'static str)> = if p.provenance.is_none() {
                vec![("provenance".to_string(), "missing; run once to refresh")]
            } else if !p.provenance.as_ref().is_some_and(|p| p.is_current()) {
                vec![("provenance".to_string(), "changed")]
            } else if p.cwd.as_deref() != Some(rel_cwd.as_str()) {
                vec![("directory".to_string(), "changed")]
            } else if &p.scope != scope {
                vec![("repository".to_string(), "changed")]
            } else if expired {
                vec![("proof".to_string(), "expired")]
            } else if &p.env != env_now {
                vec![("env".to_string(), "changed")]
            } else if p
                .env_excluded
                .iter()
                .collect::<std::collections::BTreeSet<_>>()
                != excluded_now
            {
                vec![("env exclusions".to_string(), "changed")]
            } else {
                let mut d: Vec<(String, &'static str)> = verify(root, &p.inputs, explain)
                    .into_iter()
                    .map(|m| (m.path, m.why))
                    .collect();
                if d.is_empty() {
                    // Inputs match, but a skip also needs what the run produced to be in place.
                    d = verify(root, &p.outputs, explain)
                        .into_iter()
                        .map(|m| {
                            (
                                format!("output {}", m.path),
                                if m.why == "removed" { "missing" } else { m.why },
                            )
                        })
                        .collect();
                }
                d
            };
            let mut diffs = diffs;
            if diffs.is_empty() && (!p.probes.is_empty() || !o.probes.is_empty()) {
                // External state is checked last: it can be slow, and files rule most proofs out first.
                let fresh = probe_now.get_or_insert_with(|| run_probes(&o.probes, cwd, o.quiet));
                match fresh {
                    None => diffs.push(("probe".to_string(), "failed")),
                    Some(m) if *m != p.probes => {
                        let which = m
                            .keys()
                            .chain(p.probes.keys())
                            .find(|k| m.get(*k) != p.probes.get(*k))
                            .cloned()
                            .unwrap_or_else(|| "probe".to_string());
                        diffs.push((format!("probe `{which}`"), "changed"));
                    }
                    Some(_) => {}
                }
            }
            if diffs.is_empty() {
                hit_idx = Some(i);
                break;
            }
            if i == 0 {
                let first = &diffs[0];
                let more = if diffs.len() > 1 {
                    format!(" (+{} more)", diffs.len() - 1)
                } else {
                    String::new()
                };
                why = format!("{} {}{}", shown_text(&first.0), first.1, more);
            }
            if explain {
                eprintln!("proof {} ({}):", i + 1, ago(p.created));
                for (path, w) in diffs.iter().take(20) {
                    eprintln!("  {w}: {}", shown_text(path));
                }
            }
        }
        // A run may fetch a missing proof; explain inspects only the local store.
        if hit_idx.is_some() || pulled || remote.is_none() || bypass || explain {
            break;
        }
        pulled = true;
        match remote.as_ref().map(|r| r.pull(store, key)) {
            Some(Ok(0)) | None => break,
            Some(Ok(_)) => proofs = store.load(key),
            Some(Err(e)) => {
                eprintln!("stoop: sync: could not fetch proofs ({e}); continuing");
                break;
            }
        }
    }
    Lookup {
        proofs,
        hit_idx,
        why,
        t0,
    }
}

fn legacy_finish(cx: RunCx<'_>, key: String, lookup: Lookup) -> Outcome {
    let Lookup {
        proofs,
        hit_idx,
        mut why,
        t0,
    } = lookup;
    let o = cx.o;
    let cwd = cx.cwd;
    let root = cx.root;
    let rel_cwd = cx.rel_cwd;
    let scope = cx.scope;
    let store = cx.store;
    let hook = cx.hook;
    let full_reason = cx.full_reason;
    let explain = cx.explain;
    let observe_runners = cx.observe_runners;
    let salt = cx.salt;
    let remote = &cx.remote;
    let hit: Option<&Proof> = hit_idx.map(|i| &proofs[i]);
    if let Some(p) = hit {
        if full_reason.is_none() {
            if !o.quiet {
                eprintln!(
                    "stoop: skip {key}: {} inputs unchanged since {} ({}ms)",
                    p.inputs.len(),
                    ago(p.created),
                    t0.elapsed().as_millis()
                );
            }
            return Outcome {
                status: 0,
                key,
                how: How::Skipped { proof: p.digest() },
            };
        }
        why = full_reason.clone().unwrap_or_else(|| why.clone());
    }
    if hook.is_some() {
        if let Some(reason) = full_reason {
            why.clone_from(reason);
        }
    }
    if explain {
        match hook {
            Some(h) => eprintln!(
                "stoop: would run full {key} ({why}): removed {}, argv {}",
                units::hook::show(&h.removed),
                units::hook::render(&h.argv)
            ),
            None => eprintln!("stoop: would run {key}: {why}"),
        }
        return Outcome {
            status: 1,
            key,
            how: How::Untraced,
        };
    }
    if !o.quiet {
        match hook {
            Some(h) => eprintln!(
                "stoop: run full {key} ({why}): removed {}",
                units::hook::show(&h.removed)
            ),
            None => eprintln!("stoop: run {key}: {why}"),
        }
    }

    // 2. Run it, watched. Anything that stops the watch from working just runs the command.
    let probes_before = if o.probes.is_empty() {
        Some(BTreeMap::new())
    } else {
        run_probes(&o.probes, cwd, o.quiet)
    };
    // Declaring a probe is declaring the external dependency, so network use is accepted.
    // The ignore set and the scope are fixed before the run: priors are recorded against them.
    let ignore = Ignore::new(&o.ignore, Some(&root.join(".stoopignore")), &o.transient);
    let real_root = std::fs::canonicalize(root).unwrap_or_else(|_| root.clone());
    let trace = match launch_traced(
        &cx,
        &o.argv,
        &ignore,
        &real_root,
        o.allow_network || !o.probes.is_empty(),
        observe_runners && !o.no_record && !o.quiet,
        true,
    ) {
        Ok(t) => t,
        Err(e) => {
            if !o.quiet {
                eprintln!("stoop: not traced ({e}); running without a proof");
            }
            return Outcome {
                status: plain(&o.argv, &[]),
                key,
                how: How::Untraced,
            };
        }
    };
    if let Some(line) = trace.execs.as_deref().and_then(units::diagnostic) {
        eprintln!("{line}");
    }
    let status = trace.status;
    if status != 0 {
        return Outcome {
            status,
            key,
            how: How::Failed,
        };
    }
    if o.no_record {
        return Outcome {
            status,
            key,
            how: How::Unrecorded("recording disabled".into()),
        };
    }
    // The external state the command saw must still be what it was when it finished.
    let probes = match probes_before {
        None => {
            if !o.quiet {
                eprintln!("stoop: not recorded: a probe failed before the run, so the external state is unknown");
            }
            return Outcome {
                status,
                key,
                how: How::Unrecorded("probe failed".into()),
            };
        }
        Some(before) => {
            if !o.probes.is_empty() && run_probes(&o.probes, cwd, o.quiet).as_ref() != Some(&before)
            {
                if !o.quiet {
                    eprintln!("stoop: not recorded: a probe changed while the command ran");
                }
                return Outcome {
                    status,
                    key,
                    how: How::Unrecorded("probe changed".into()),
                };
            }
            before
        }
    };

    // 3. It passed: write down what it read, what it wrote, and what each written path held before.
    match assemble(root, &real_root, &trace, &ignore) {
        Ok(Assembled {
            inputs,
            outputs,
            removed,
            priors,
            read_reasons,
            write_reasons,
        }) => {
            let n = inputs.len();
            let proof = Proof {
                created: now(),
                argv: o
                    .argv
                    .iter()
                    .map(|word| word.to_string_lossy().into_owned())
                    .collect(),
                cwd: Some(rel_cwd.clone()),
                scope: scope.clone(),
                provenance: Some(trace::Provenance::current()),
                env: cx.env_now,
                env_excluded: cx.env_excluded,
                inputs,
                outputs,
                probes,
                removed,
                ignore: Some(ignore.patterns()),
                priors: Some(priors),
                unplannable: merge_reasons(
                    &trace.unplannable,
                    read_reasons.into_iter().chain(write_reasons).collect(),
                ),
            };
            let digest = proof.digest();
            if let Some(r) = remote.as_ref().filter(|r| r.write) {
                // Fold in anything other runs published since we looked, so a push never
                // drops their proofs.
                if let Err(e) = r.pull(store, &key) {
                    eprintln!("stoop: sync: could not refresh from the remote ({e}); continuing");
                }
            }
            let saved = match store.save(&key, proof) {
                Ok(()) => {
                    if !o.quiet {
                        eprintln!("stoop: recorded {n} inputs for {key}");
                    }
                    true
                }
                Err(e) => {
                    eprintln!("stoop: could not save proof: {e}");
                    false
                }
            };
            if let Some(r) = remote
                .as_ref()
                .filter(|r| saved && r.write && !o.defer_push)
            {
                if salt.is_none() {
                    // Hashes of every variable go into a file other people can fetch. An
                    // unsalted hash of a low-entropy secret can be guessed offline.
                    eprintln!(
                        "stoop: sync: publishing environment hashes without {SALT_VAR}. In a public repository set it from a repository secret so low-entropy values cannot be guessed offline."
                    );
                }
                match r.push(store, &key) {
                    Ok(()) if !o.quiet => eprintln!("stoop: published {key} to the remote"),
                    Ok(()) => {}
                    Err(e) => eprintln!("stoop: sync: could not publish ({e}); continuing"),
                }
            }
            return Outcome {
                status,
                key,
                how: if saved {
                    How::Recorded { proof: digest }
                } else {
                    How::Unrecorded("could not save proof".into())
                },
            };
        }
        Err(why) => {
            if !o.quiet {
                eprintln!("stoop: not recorded: {why}");
            }
        }
    }
    Outcome {
        status,
        key,
        how: How::Unrecorded("inputs could not be recorded".into()),
    }
}

/// One traced launch of `argv`. `capture_blob_ids` takes the repository's attribute snapshot, which
/// gives each input its Git blob id. A unit launch passes `false`: its proof carries no blob id, and
/// the snapshot costs several Git probes per launch (spec T2).
pub(crate) fn launch_traced(
    cx: &RunCx<'_>,
    argv: &[OsString],
    ignore: &Ignore,
    real_root: &Path,
    allow_network: bool,
    observe_execs: bool,
    capture_blob_ids: bool,
) -> std::io::Result<Trace> {
    let trace_scope = (!cx.o.no_record).then(|| trace::Scope {
        root: cx.root,
        real_root: real_root.to_path_buf(),
        ignore,
        // One attribute snapshot per run, taken before the command can change anything. A unit
        // launch takes none, because its proof records no blob id and nothing reads one (spec T2).
        oid_epoch: (capture_blob_ids && trace::supported())
            .then(|| crate::oid_attrs::capture(real_root))
            .flatten()
            .map(Arc::new),
    });
    trace::run(
        argv,
        cx.cwd,
        allow_network,
        trace_scope.as_ref(),
        observe_execs,
    )
}

pub(crate) struct Assembled {
    pub(crate) inputs: Vec<Input>,
    pub(crate) outputs: Vec<Input>,
    removed: Vec<String>,
    priors: Vec<Input>,
    read_reasons: Vec<String>,
    write_reasons: Vec<String>,
}

pub(crate) fn assemble(
    root: &Path,
    real_root: &Path,
    trace: &Trace,
    ignore: &Ignore,
) -> Result<Assembled, NotRecorded> {
    assemble_with(root, real_root, trace, ignore, RootListing::Drop)
}

/// `assemble`, with the root listing decided by the caller (see `RootListing`).
pub(crate) fn assemble_with(
    root: &Path,
    real_root: &Path,
    trace: &Trace,
    ignore: &Ignore,
    root_listing: RootListing,
) -> Result<Assembled, NotRecorded> {
    let mut phys = Physical::new(root, real_root);
    let written: BTreeSet<String> = trace.keys.values().cloned().collect();
    let (mut inputs, read_reasons) =
        build_inputs_with(root, &mut phys, trace, ignore, &written, root_listing)?;
    let (outputs, removed, write_reasons, verified) = build_outputs(real_root, &written, trace);
    let priors = build_priors(trace);
    if !verified.is_empty() {
        let original_len = inputs.len();
        for key in verified {
            if inputs[..original_len]
                .binary_search_by(|input| input.path.cmp(&key))
                .is_ok()
            {
                continue;
            }
            if let Ok(index) = priors.binary_search_by(|prior| prior.path.cmp(&key)) {
                inputs.push(priors[index].clone());
            }
        }
        inputs.sort_by(|a, b| a.path.cmp(&b.path));
    }
    Ok(Assembled {
        inputs,
        outputs,
        removed,
        priors,
        read_reasons,
        write_reasons,
    })
}

fn landing_verified(
    trace: &Trace,
    key: &str,
    id: Option<&str>,
    post: &trace::identity::Post,
) -> bool {
    !trace.footprint.unknown
        && !trace::identity::link_route_unknown(&trace.footprint)
        && trace.atomic_landings.get(key).is_some_and(|landing| {
            matches!(post, trace::identity::Post::File { stat, hash }
            if *stat == landing.stat
                && id.is_some_and(|id| {
                    id == crate::input::file_id(landing.stat.mode & 0o111 != 0, hash)
                }))
        })
}

/// What the run left behind inside the repository, read once it finished: one entry for each
/// in-scope path it wrote. Still there is an output. Gone again is removed, and the planner
/// removes it with the step. Unreadable or special is a reason the planner cannot replay.
fn build_outputs(
    real_root: &Path,
    written: &BTreeSet<String>,
    trace: &Trace,
) -> (Vec<Input>, Vec<String>, Vec<String>, Vec<String>) {
    let keys: Vec<&String> = written.iter().collect();
    let ids = par_map(&keys, |k| {
        identify_post(&real_root.join(k.as_str()), true, false, false, false)
    });
    let mut outputs = Vec::new();
    let mut removed = Vec::new();
    let mut reasons = Vec::new();
    let mut verified = Vec::new();
    for (key, (id, post)) in keys.into_iter().zip(ids) {
        let output_id = id.as_ref().map(|(id, _)| id.as_str());
        let direct = trace.bound_priors.contains(key)
            && output_id.is_some_and(|id| {
                (id.starts_with("f:") || id.starts_with("x:"))
                    && trace.priors.get(key).is_some_and(|prior| prior != id)
            });
        if direct || landing_verified(trace, key, output_id, &post) {
            verified.push(key.clone());
        }
        match id.map(|(id, _)| id) {
            None => reasons.push(format!("it left {key} unreadable")),
            Some(id) if id == "u" => reasons.push(format!("it left {key} unreadable")),
            Some(id) if id == "a" => removed.push(key.clone()),
            Some(id) => outputs.push(Input {
                path: key.clone(),
                id,
                oid: None,
                oid_basis: None,
            }),
        }
    }
    if written.contains(".stoopignore") {
        reasons.push("it wrote .stoopignore, which the proof's ignore set was read from".into());
    }
    (outputs, removed, reasons, verified)
}

/// The state of each in-scope path before the run first wrote it, sorted by path.
pub fn build_priors(trace: &Trace) -> Vec<Input> {
    trace
        .priors
        .iter()
        .map(|(path, id)| {
            let basis = (!trace.oid_attrs_changed)
                .then(|| trace.prior_oid_bases.get(path))
                .flatten();
            let oid = basis
                .filter(|basis| basis.allows_oid())
                .and_then(|_| trace.prior_oids.get(path).cloned());
            let oid_basis = basis.cloned();
            Input {
                path: path.clone(),
                id: id.clone(),
                oid,
                oid_basis,
            }
        })
        .collect()
}

/// The proof's reasons: the tracer's first, then the rest, deduplicated and capped at 16.
fn merge_reasons(first: &[String], more: Vec<String>) -> Vec<String> {
    let mut out: Vec<String> = Vec::new();
    for why in first.iter().cloned().chain(more) {
        if out.len() < 16 && !out.contains(&why) {
            out.push(why);
        }
    }
    out
}

/// A changed candidate or an existing recorder refusal.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum NotRecorded {
    Changed { key: String },
    Other(String),
}

impl std::fmt::Display for NotRecorded {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Changed { key } => write!(formatter, "{key} changed while the command ran"),
            Self::Other(reason) => formatter.write_str(reason),
        }
    }
}

impl From<String> for NotRecorded {
    fn from(reason: String) -> Self {
        Self::Other(reason)
    }
}

impl From<&str> for NotRecorded {
    fn from(reason: &str) -> Self {
        Self::Other(reason.to_owned())
    }
}

/// `Ok(Some(reason))` leaves the candidate at its v9 outcome; `Err` means it changed.
fn compare_candidate(
    trace: &Trace,
    path: &Path,
    listed: bool,
    post: &trace::identity::Post,
) -> Result<Option<trace::identity::Skip>, ()> {
    let Some(seen) = &trace.seen else {
        return Ok(None);
    };
    let observation = seen.get(path);
    let was_listed = trace.listings.contains_key(path);
    if let Some(reason) = trace::identity::skip(
        &trace.footprint,
        observation,
        path,
        listed || was_listed,
        post,
    ) {
        return Ok(Some(reason));
    }
    let observation = observation.expect("skip rejects missing observations");
    let listing = if listed {
        trace.listings.get(path)
    } else {
        None
    };
    if listed && matches!(observation.seen, trace::identity::Seen::Dir(_)) && listing.is_none() {
        return Ok(Some(trace::identity::Skip::NotObserved));
    }
    if trace::identity::matches(observation, post, listing) {
        Ok(None)
    } else {
        Err(())
    }
}

/// Whether a listed repository root is an input. Only unit proofs record it, so the legacy path and
/// whole-command proofs keep their bytes (pin P10).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum RootListing {
    /// A listed root is the input `.`, with the same `dl:` id a listed directory gets.
    Record,
    /// The root is never an input, as on the legacy path.
    Drop,
}

/// What the run read, as comparable inputs, or why it cannot be trusted. A read of a path the
/// run wrote is not an input: it reads the run's own output. A read through a link or a
/// symlinked directory is also recorded under the key of the file it reached, so a change to
/// that file is seen. The second value holds reasons the planner cannot replay the run.
#[cfg(test)]
#[cfg_attr(not(any(target_os = "linux", target_os = "macos")), allow(dead_code))]
pub fn build_inputs(
    root: &Path,
    phys: &mut Physical,
    trace: &Trace,
    ignore: &Ignore,
    written: &BTreeSet<String>,
) -> Result<(Vec<Input>, Vec<String>), NotRecorded> {
    build_inputs_with(root, phys, trace, ignore, written, RootListing::Drop)
}

/// `build_inputs`, with the root listing decided by the caller. Only unit proofs pass `Record`.
pub(crate) fn build_inputs_with(
    root: &Path,
    phys: &mut Physical,
    trace: &Trace,
    ignore: &Ignore,
    written: &BTreeSet<String>,
    root_listing: RootListing,
) -> Result<(Vec<Input>, Vec<String>), NotRecorded> {
    if let Some(u) = trace.unsound.first() {
        return Err(u.clone().into());
    }
    let paths = trace
        .touched
        .keys()
        .chain(&trace.written)
        .chain(&trace.created_dirs);
    for path in paths {
        if path.strip_prefix(root).unwrap_or(path).to_str().is_none() {
            return Err("a traced path is not valid UTF-8".into());
        }
    }
    // Symlink targets are serialized as text too. Refuse rather than serialize lossy bytes.
    for path in trace.keys.keys().chain(trace.touched.keys()) {
        let in_repo = path.starts_with(root) || path.starts_with(phys.real());
        if in_repo
            && std::fs::symlink_metadata(path).is_ok_and(|m| m.file_type().is_symlink())
            && std::fs::read_link(path).is_ok_and(|target| target.to_str().is_none())
        {
            return Err("it used a repository symlink with a non-UTF-8 target".into());
        }
    }
    let real_root = phys.real().to_path_buf();
    phys.prefetch(
        trace
            .touched
            .keys()
            .filter_map(|p| p.parent().map(Path::to_path_buf)),
    );
    let mut reasons: Vec<String> = Vec::new();
    let mut reads_git = false;
    // (path, key, lexical inside, entries listed, repository-relative physical key)
    let mut cands: Vec<(PathBuf, String, bool, bool, Option<String>)> = Vec::new();
    for (lex, touch) in &trace.touched {
        let inside = lex.starts_with(root);
        let key = to_key(root, lex);
        let physical = phys.locate(lex).map(|l| l.path);
        // The same entry reached under its physical name, when that differs from the spelled one.
        if let Some(pp) = &physical {
            if let Some(rel) = phys.repo_rel(pp) {
                match rel.to_str() {
                    None => {
                        return Err(
                            "it used a path in the repository that is not valid UTF-8".into()
                        )
                    }
                    Some(pkey) if pkey != key => {
                        if rel.components().any(|c| is_git_name(c.as_os_str())) {
                            if !ignore.is_ignored(pkey) {
                                reads_git = true;
                            }
                        } else if ignore.is_ignored(pkey) {
                        } else if written.contains(pkey) {
                            reasons.push(format!("it read {pkey} through {key} and also wrote it"));
                        } else {
                            cands.push((
                                pp.clone(),
                                pkey.to_string(),
                                true,
                                touch.listed,
                                Some(pkey.to_string()),
                            ));
                        }
                    }
                    Some(_) => {}
                }
            }
        }
        // A lexical key containing `..` does not describe kernel resolution across a
        // symlink. The physical candidate above is the only faithful repository key.
        if lex
            .components()
            .any(|part| matches!(part, std::path::Component::ParentDir))
        {
            continue;
        }
        // The repository root is `.` for unit proofs when its launch listed it. The tracer keeps it
        // only while "" is not ignored (`record_touch`); the same test decides here. A root that was
        // only stat'ed records nothing. A launch that wrote a top-level entry itself is not compared
        // against the root (`identity::skip`), so `.` is the listing after that launch.
        if root_listing == RootListing::Record && key.is_empty() {
            if touch.listed && !ignore.is_ignored("") {
                cands.push((lex.clone(), ".".to_owned(), inside, true, None));
            }
            continue;
        }
        if key.is_empty() || ignore.is_ignored(&key) {
            continue;
        }
        if inside
            && lex
                .strip_prefix(root)
                .ok()
                .and_then(|r| r.to_str())
                .is_none()
        {
            return Err("it used a path in the repository that is not valid UTF-8".into());
        }
        let written_physically = physical
            .as_deref()
            .and_then(|pp| phys.repo_rel(pp))
            .and_then(|r| r.to_str())
            .is_some_and(|k| written.contains(k));
        if trace.is_output(lex) || written_physically {
            continue;
        }
        if inside && key.split('/').any(|c| is_git_name(OsStr::new(c))) {
            reads_git = true;
            continue;
        }
        let physical_key = physical
            .as_deref()
            .and_then(|p| phys.repo_rel(p))
            .and_then(Path::to_str)
            .filter(|_| inside)
            .map(str::to_owned);
        cands.push((lex.clone(), key, inside, touch.listed, physical_key));
    }
    // A symlink hides a second file: record where it points, whether or not the link is
    // ignored (an alias under an ignored /tmp can point into the repository).
    for lex in trace.touched.keys() {
        if trace.magic_links.contains(lex) {
            continue;
        }
        if !std::fs::symlink_metadata(lex).is_ok_and(|m| m.file_type().is_symlink()) {
            continue;
        }
        // Proc magic links are resolved while the tracee is stopped. Resolving them
        // here would instead use the recorder's own process and working directory.
        if std::fs::read_link(lex)
            .is_ok_and(|target| target.starts_with("/proc") || target.starts_with("/dev/fd"))
        {
            continue;
        }
        let Ok(target) = std::fs::canonicalize(lex) else {
            continue;
        };
        if target == real_root {
            continue;
        }
        let link_key = to_key(root, lex);
        match target.strip_prefix(&real_root) {
            Ok(rel) if !rel.as_os_str().is_empty() => {
                let Some(tkey) = rel.to_str() else {
                    return Err("it used a path in the repository that is not valid UTF-8".into());
                };
                if rel.components().any(|c| is_git_name(c.as_os_str())) {
                    if !ignore.is_ignored(tkey) {
                        reads_git = true;
                    }
                    continue;
                }
                if ignore.is_ignored(tkey) {
                    continue;
                }
                if written.contains(tkey) {
                    reasons.push(format!(
                        "it read {tkey} through {link_key} and also wrote it"
                    ));
                    continue;
                }
                cands.push((
                    target.clone(),
                    tkey.to_string(),
                    true,
                    false,
                    Some(tkey.to_string()),
                ));
            }
            _ => {
                if target
                    .strip_prefix(root)
                    .unwrap_or(&target)
                    .to_str()
                    .is_none()
                {
                    return Err("a symlink target is not valid UTF-8".into());
                }
                let tk = to_key(root, &target);
                if ignore.is_ignored(&link_key) || ignore.is_ignored(&tk) {
                    continue;
                }
                cands.push((target.clone(), tk, false, false, None));
            }
        }
    }
    if reads_git {
        return Err("it reads .git, so a skip could hide a history change (add `.git` to .stoopignore if that read cannot change the result)".into());
    }
    // All known paths share the snapshot taken before the command started. A
    // changed attribute source makes both its OIDs and its evidence stale.
    let epoch = trace
        .oid_epoch
        .as_deref()
        .filter(|_| !trace.oid_attrs_changed);
    // Tests also build synthetic traces without starting a traced command.
    #[cfg(test)]
    let synthetic_epoch =
        if epoch.is_none() && !trace.oid_epoch_captured && !trace.oid_attrs_changed {
            crate::oid_attrs::snapshot(&real_root)
        } else {
            None
        };
    #[cfg(test)]
    let epoch = epoch.or(synthetic_epoch.as_ref());
    let ids = par_map(&cands, |(path, key, inside, listed, physical_key)| {
        let basis = physical_key
            .as_ref()
            .and_then(|physical| epoch.and_then(|epoch| epoch.basis.get(physical)));
        // A Git OID names the blob at the input's own tree path. A read reached through
        // another spelling (a directory alias) keeps its evidence but claims no OID.
        let names_tree_path = physical_key.as_deref() == Some(key.as_str());
        let with_oid = names_tree_path && basis.is_some_and(|basis| basis.allows_oid());
        let need_names = trace
            .listings
            .get(path)
            .is_some_and(|listing| listing.names.is_some());
        let (id, post) = identify_post(path, *inside, *listed, with_oid, need_names);
        let id = id.map(|(id, oid)| {
            // Evidence describes a file's attributes even when conversion or a
            // length-changing read prevents a raw Git OID from being emitted.
            let oid_basis = (id.starts_with("f:") || id.starts_with("x:"))
                .then(|| basis.cloned())
                .flatten();
            (id, oid, oid_basis)
        });
        (id, post)
    });
    let mut out: Vec<Input> = Vec::with_capacity(cands.len());
    let mut seen: HashSet<String> = HashSet::new();
    let debug = std::env::var_os("STOOP_DEBUG").is_some();
    let mut skipped = Vec::new();
    let mut changed: Option<&str> = None;
    for ((path, key, _, listed, _), (id, post)) in cands.iter().zip(ids) {
        match compare_candidate(trace, path, *listed, &post) {
            Ok(Some(reason)) if debug => skipped.push((key.as_str(), reason)),
            Ok(_) => {}
            Err(()) => {
                if changed.is_none_or(|first| key.as_str() < first) {
                    changed = Some(key);
                }
            }
        }
        if let Some((id, oid, oid_basis)) = id {
            if seen.insert(key.clone()) {
                out.push(Input {
                    path: key.clone(),
                    id,
                    oid,
                    oid_basis,
                });
            }
        }
    }
    if debug {
        skipped
            .sort_by(|(a, _), (b, _)| a.starts_with('/').cmp(&b.starts_with('/')).then(a.cmp(b)));
        for (key, reason) in skipped.into_iter().take(32) {
            eprintln!("stoop: debug: not compared {key}: {reason:?}");
        }
    }
    if let Some(key) = changed {
        return Err(NotRecorded::Changed {
            key: key.to_owned(),
        });
    }
    out.sort_by(|a, b| a.path.cmp(&b.path));
    Ok((out, reasons))
}

